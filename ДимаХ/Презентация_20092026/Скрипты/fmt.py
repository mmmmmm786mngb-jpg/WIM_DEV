# -*- coding: utf-8 -*-
"""
Единые правила отображения чисел для пакета презентаций 20.09.2026.

Логика подачи цифр руководству:
  * заголовки, KPI, выводы  - округленно (money_head / money_mln): "1,2 млн"
  * диаграммы и сводные таблицы - в тысячах (num_ths), единица - в подписи оси
  * таблица-первоисточник   - точная сумма до рубля (rub)

Модуль подключается всеми сборщиками презентаций, чтобы формат чисел
не расходился между слайдами и файлами.
"""

import math


def rub(value):
    """Точная сумма в рублях с разделителями разрядов (для таблицы-первоисточника).

    Параметры:
      value - Число - сумма в рублях

    Возвращаемое значение:
      Строка - например "1 229 955"
    """
    return "{:,}".format(int(round(value))).replace(",", "\u00a0")


def money_mln(value):
    """Сумма в миллионах для крупных заголовков.

    Параметры:
      value - Число - сумма в рублях

    Возвращаемое значение:
      Строка - например "1,2 млн"
    """
    return ("%.1f" % (value / 1000000.0)).replace(".", ",") + "\u00a0млн"


def money_head(value):
    """Крупная сумма для KPI и выводов: млн при значении от 1 млн, иначе тыс.

    Параметры:
      value - Число - сумма в рублях

    Возвращаемое значение:
      Строка - например "1,2 млн" или "411 тыс."
    """
    if abs(value) >= 1000000:
        return money_mln(value)
    return "{:,}".format(int(round(value / 1000.0))).replace(",", "\u00a0") + "\u00a0тыс."


def num_ths(value):
    """Число в тысячах для подписей диаграмм и сводных таблиц.

    Единица измерения выносится в заголовок столбца или подпись оси.

    Параметры:
      value - Число - сумма в рублях

    Возвращаемое значение:
      Строка - например "445" (из 444600) или "3,9" (из 3900)
    """
    k = value / 1000.0
    if abs(k) < 0.05:
        return "0"
    if abs(k) < 10:
        return ("%.1f" % k).replace(".", ",")
    return "{:,}".format(int(round(k))).replace(",", "\u00a0")


def ratio(value):
    """Кратность без лишних нулей.

    Параметры:
      value - Число - отношение величин

    Возвращаемое значение:
      Строка - например "4" (из 3.99) или "3,5"
    """
    if abs(value - round(value)) < 0.05:
        return str(int(round(value)))
    return ("%.1f" % value).replace(".", ",")


def fte_months(hours, month_hours=168.0):
    """Человеко-месяцы: 21 рабочий день x 8 часов = 168 ч.

    Параметры:
      hours       - Число - человеко-часы
      month_hours - Число - часов в одном человеко-месяце

    Возвращаемое значение:
      Строка - например "2,5"
    """
    value = hours / float(month_hours)
    if abs(value - round(value)) < 0.05:
        return str(int(round(value)))
    return ("%.1f" % value).replace(".", ",")


def hrs(value):
    """Часы без лишних нулей.

    Параметры:
      value - Число - количество часов

    Возвращаемое значение:
      Строка - например "314" или "313,75"
    """
    if abs(value - round(value)) < 0.01:
        return num_int(value)
    formatted = ("%.2f" % value).rstrip("0").rstrip(".").replace(".", ",")
    if "," in formatted:
        whole, frac = formatted.split(",", 1)
        try:
            whole = num_int(int(whole))
        except ValueError:
            pass
        return whole + "," + frac
    return formatted


def num_int(value):
    """Целое с разделителями разрядов: 1065 -> '1 065'."""
    return "{:,}".format(int(round(value))).replace(",", "\u00a0")


def pct(value):
    """Процент без лишнего знака после запятой, если он нулевой."""
    if abs(value - round(value)) < 0.05:
        return str(int(round(value)))
    return ("%.1f" % value).replace(".", ",")


# Множители "круглого" шага шкалы. Набор плотнее, чем классический 1/2/5:
# иначе при шаге чуть больше 5x10^n шкала прыгает на порядок и данные
# занимают половину диаграммы (например ось до 4 млн при максимуме 2,2 млн).
NICE_STEPS = (1, 1.5, 2, 2.5, 3, 4, 5, 6, 7.5, 8, 10)


def nice_max(value, ticks):
    """Верх шкалы, округленный вверх до круглого шага.

    Нужен, чтобы деления оси читались как 0 - 100 - 200 - 300, а не 0 - 111 - 222,
    и при этом данные занимали большую часть высоты диаграммы.

    Параметры:
      value - Число - максимальное значение данных
      ticks - Число - количество делений оси

    Возвращаемое значение:
      Число - верхняя граница шкалы, кратная выбранному шагу.
    """
    if value <= 0:
        return float(ticks)
    raw_step = value / float(ticks)
    exp = math.floor(math.log10(raw_step))
    for mult in NICE_STEPS:
        step = mult * (10.0 ** exp)
        if step >= raw_step:
            return step * ticks
    return (10.0 ** (exp + 1)) * ticks
