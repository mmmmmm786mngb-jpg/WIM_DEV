def read_ib_path():
    here = os.path.dirname(os.path.abspath(__file__))
    sp = os.path.normpath(os.path.join(here, "..", "..", "..", "source-path.txt"))
    with open(sp, "r", encoding="utf-8") as f:
        return f.read().strip()


def dump_query(conn, name, text, out_dir):
    q = conn.NewObject("Запрос")
    q.Текст = text
    table = q.Выполнить().Выгрузить()
    cols = [c.Имя for c in table.Колонки]
    rows = []
    n = table.Количество()
    for i in range(n):
        row = table.Get(i)
        rec = {}
        for c in cols:
            try:
                rec[c] = str(getattr(row, c))
            except Exception:
                rec[c] = ""
        rows.append(rec)
    payload = {"name": name, "count": n, "cols": cols, "rows": rows[:300]}
    path = os.path.join(out_dir, "q_%s.json" % name)
    with open(path, "w", encoding="utf-8") as f:
        json.dump(payload, f, ensure_ascii=False, indent=2)
    print("query %s rows=%s -> %s" % (name, n, path))


