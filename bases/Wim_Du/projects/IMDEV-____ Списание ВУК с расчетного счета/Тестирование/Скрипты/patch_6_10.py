    with open(PATH, "rb") as f:
        raw = f.read()
    text = raw.decode("utf-8-sig").replace("\r\n", "\n")
    for old, new in R:
        # хвостовые пробелы строк в исходнике не значимы и могли не сохраниться в шаблоне
        lines = old.replace("\r\n", "\n").split("\n")
        pattern = r"[ \t]*\n".join(re.escape(ln.rstrip(" \t")) for ln in lines) + r"[ \t]*"
        found = re.findall(pattern, text)
        if len(found) != 1:
            raise SystemExit(f"найдено {len(found)} раз: {lines[0][:80]!r}")
        text = re.sub(pattern, lambda m: new.replace("\r\n", "\n"), text)
    with open(PATH, "wb") as f:
        f.write(b"\xef\xbb\xbf" + text.replace("\n", "\r\n").encode("utf-8"))
