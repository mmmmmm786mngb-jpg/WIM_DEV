def html_esc(s: str) -> str:
    return s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


def wrap_pre(bsl: str, css: str = "") -> str:
    cls = ' class="%s"' % css if css else ""
    return "<pre%s>%s</pre>" % (cls, html_esc(bsl.strip("\n")))


def extract_query_literal(lines, start, end) -> str:
    chunk = []
    for line in lines[start - 1 : end]:
        raw = line.rstrip("\r\n").rstrip()
        # Assignment indent varies (2 or 3 tabs). Keep | and the opening quote.
        stripped = raw.lstrip("\t ")
        chunk.append(stripped)
    text = "\n".join(chunk)
    if text.endswith(";"):
        text = text[:-1].rstrip()
    if not (text.startswith('"') and text.endswith('"')):
        raise RuntimeError("Query literal bounds mismatch: %r ... %r" % (text[:40], text[-40:]))
    return text


def indent_block(text: str, n: int) -> str:
    pad = " " * n
    return "\n".join(pad + ln if ln else "" for ln in text.split("\n"))


def replace_between(html: str, start: str, end: str, new: str) -> str:
    i = html.find(start)
    if i < 0:
        raise RuntimeError("Start marker not found: %s" % start[:80])
    j = html.find(end, i)
    if j < 0:
        raise RuntimeError("End marker not found after start: %s" % end[:80])
    return html[:i] + new + html[j:]


