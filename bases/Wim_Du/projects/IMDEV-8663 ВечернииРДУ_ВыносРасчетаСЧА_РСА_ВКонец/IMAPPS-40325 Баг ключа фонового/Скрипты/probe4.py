"""IMAPPS-40325: виды операций закрытия периода на dev WIM_DU и префиксы договоров."""
import os, sys
import pythoncom, win32com.client
sys.stdout.reconfigure(encoding='utf-8')
pythoncom.CoInitialize()
c = win32com.client.Dispatch('V83.COMConnector').Connect('Srvr="localhost";Ref="WIM_DU";')
def run(text, **p):
    q = c.NewObject('Запрос'); q.Текст = text
    for k, v in p.items(): q.УстановитьПараметр(k, v)
    r = q.Выполнить(); s = r.Выбрать(); n = r.Колонки.Количество(); out = []
    while s.Следующий(): out.append([str(s.Получить(j)) for j in range(n)])
    return out
for r in run('''ВЫБРАТЬ ВидыОпер.Код КАК Код, ВидыОпер.Наименование КАК Наим, ПРЕДСТАВЛЕНИЕ(ВидыОпер.Родитель) КАК Родитель,
 ВидыОпер.Отключить КАК Откл, ВидыОпер.БезДокумента КАК БезДок, ВидыОпер.ОбщаяОперация КАК Общ,
 ВЫРАЗИТЬ(ВидыОпер.ИсполняемаяПроцедура КАК СТРОКА(200)) КАК Проц, ВидыОпер.Предопределенный КАК Пред
 ИЗ Справочник.ВидыОперацийЗакрытияПериода КАК ВидыОпер ГДЕ НЕ ВидыОпер.ЭтоГруппа УПОРЯДОЧИТЬ ПО ВидыОпер.Родитель.Код, ВидыОпер.Код'''):
    print('|'.join(r))
print('Префиксы', run('''ВЫБРАТЬ КОЛИЧЕСТВО(*) КАК Всего, СУММА(ВЫБОР КОГДА Д.Префикс <> "" ТОГДА 1 ИНАЧЕ 0 КОНЕЦ) КАК СПрефиксом,
 СУММА(ВЫБОР КОГДА Д.ДатаОкончания = ДАТАВРЕМЯ(1,1,1) ТОГДА 1 ИНАЧЕ 0 КОНЕЦ) КАК БезОкончания ИЗ Справочник.ДоговорДУ КАК Д ГДЕ НЕ Д.ПометкаУдаления'''))
print('Группы', run('ВЫБРАТЬ В.Код КАК К, ПРЕДСТАВЛЕНИЕ(В.Родитель) КАК Р, В.ВремяРеглОпераций КАК Вр ИЗ Справочник.ВидыОперацийЗакрытияПериода КАК В ГДЕ В.ЭтоГруппа'))
sys.stdout.flush(); os._exit(0)
