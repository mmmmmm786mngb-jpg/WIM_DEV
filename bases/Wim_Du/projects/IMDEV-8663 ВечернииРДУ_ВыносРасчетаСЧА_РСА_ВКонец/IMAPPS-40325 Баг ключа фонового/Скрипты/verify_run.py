"""IMAPPS-40325: проверка результата прогона - планы по портфелям стенда и события ЖР с ошибкой ключа."""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import stand
c = stand.connect()
day = stand.make_date(c, *stand.TEST_DAY)
t = stand.query(c, """ВЫБРАТЬ Планы.ДоговорДУ.Портфель КАК Портфель, Планы.Проведен КАК Проведен, КОЛИЧЕСТВО(*) КАК Количество,
 МАКСИМУМ(Планы.Дата) КАК Макс
 ИЗ Документ.ПланРегламентныхОперацийДУ КАК Планы
 ГДЕ Планы.Дата МЕЖДУ &Н И &К И Планы.ДоговорДУ.Портфель ПОДОБНО "T40325%" И НЕ Планы.ПометкаУдаления
 СГРУППИРОВАТЬ ПО Планы.ДоговорДУ.Портфель, Планы.Проведен""", Н=day, К=stand.make_date(c, *stand.TEST_DAY, 23, 59, 59))
for i in range(t.Количество()):
    r = t.Получить(i)
    print('Планы', r.Портфель, 'проведен' if r.Проведен else 'НЕ проведен', r.Количество)
since = stand.make_date(c, *[int(x) for x in sys.argv[1].split('-')]) if len(sys.argv) > 1 else day
log = c.NewObject('ТаблицаЗначений')
flt = c.NewObject('Структура')
flt.Вставить('Событие', 'РегламентныеОперации')
c.ВыгрузитьЖурналРегистрации(log, flt)
print('Событий РегламентныеОперации всего:', log.Количество())
for i in range(log.Количество()):
    r = log.Получить(i)
    print(str(r.Дата), '|', str(r.ПредставлениеПриложения), '|', str(r.Комментарий)[:160].replace('\n', ' '))
sys.stdout.flush(); os._exit(0)
