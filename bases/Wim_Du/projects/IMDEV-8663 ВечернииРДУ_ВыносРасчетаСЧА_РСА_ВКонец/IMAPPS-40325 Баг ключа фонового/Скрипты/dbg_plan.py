# -*- coding: utf-8 -*-
"""IMAPPS-40325: отладка стенда - ПланРеглОпераций по договорам портфеля А."""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import stand
c = stand.connect()
day = stand.make_date(c, *stand.TEST_DAY)
t = stand.query(c, 'ВЫБРАТЬ Договоры.Ссылка КАК Ссылка ИЗ Справочник.ДоговорДУ КАК Договоры ГДЕ Договоры.Портфель = &П', П=stand.PORTFOLIO_A)
arr = c.NewObject('Массив')
for i in range(t.Количество()): arr.Добавить(t.Получить(i).Ссылка)
g = stand.evening_group(c)
plan = c.РегистрыСведений.НастройкиЗакрытияПериода.ПланРеглОпераций(day, arr, g)
print('План с группой', plan.Количество())
plan2 = c.РегистрыСведений.НастройкиЗакрытияПериода.ПланРеглОпераций(day, arr)
print('План без группы', plan2.Количество())
for name, text in [('Регистр', 'ВЫБРАТЬ КОЛИЧЕСТВО(*) КАК К ИЗ РегистрСведений.НастройкиЗакрытияПериода КАК Н'),
                   ('Кэш', 'ВЫБРАТЬ КОЛИЧЕСТВО(*) КАК К ИЗ РегистрСведений.КэшВидовПериодичности КАК Кэш ГДЕ Кэш.ДатаПериодичности = &Д'),
                   ('УП', 'ВЫБРАТЬ КОЛИЧЕСТВО(*) КАК К ИЗ РегистрСведений.УчетныеПолитики КАК УП'),
                   ('ДокУмолч', 'ВЫБРАТЬ КОЛИЧЕСТВО(*) КАК К ИЗ Документ.УстановкаРеглОперацийДУ КАК У ГДЕ У.Проведен И У.ДоговорДУ = ЗНАЧЕНИЕ(Справочник.ДоговорДУ.ПустаяСсылка) И У.Дата <= &Д')]:
    print(name, stand.query(c, text, Д=day).Получить(0).К)
sys.stdout.flush(); os._exit(0)
