def collect():
    """Прогоняет патч на базовых модулях и возвращает [(заголовок модуля, путь, [(метка, найти, заменить)])]."""
    result = []
    for title, rel, func in ((MANAGER_TITLE, patch.MANAGER, patch.patch_manager),
                             (FORM_TITLE, patch.FORM_MODULE, patch.patch_form)):
        text, _, _ = patch.read(os.path.join(patch.SRC, rel))
        patch.APPLIED.clear()
        patched = func(text)
        result.append((title, rel, list(patch.APPLIED), text, patched))
    return result


