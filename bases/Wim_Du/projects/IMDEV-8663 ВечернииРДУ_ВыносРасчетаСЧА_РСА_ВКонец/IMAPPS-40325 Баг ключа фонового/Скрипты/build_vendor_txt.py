def verify(path, modules):
    """Разбирает записанный файл и применяет его правки к базовым модулям: результат = модули CF."""
    with open(path, encoding="utf-8-sig") as f:
        text = f.read().replace("\r\n", "\n")
    blocks = re.findall(re.escape(FIND) + r"\n(.*?)\n" + re.escape(REPLACE) + r"\n(.*?)\n" + re.escape(END),
                        text, re.S)
    index = 0
    for title, _rel, changes, before, after in modules:
        current = before
        for _ in changes:
            old, new = blocks[index]
            index += 1
            if current.count(old + "\n") != 1:
                raise RuntimeError("%s: фрагмент НАЙТИ правки %d найден не один раз" % (title, index))
            current = current.replace(old + "\n", new + "\n")
        if current != after:
            raise RuntimeError("%s: результат по инструкции не совпадает с модулем CF" % title)
        print("Проверено:", title, "- правок", len(changes), ", результат совпадает с CF")
    if index != len(blocks):
        raise RuntimeError("В файле лишние блоки правок")


