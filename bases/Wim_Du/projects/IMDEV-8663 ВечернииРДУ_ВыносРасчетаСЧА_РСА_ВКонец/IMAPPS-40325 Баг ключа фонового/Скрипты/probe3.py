import os, sys
import pythoncom, win32com.client
sys.stdout.reconfigure(encoding='utf-8')
pythoncom.CoInitialize()
c = win32com.client.Dispatch('V83.COMConnector').Connect('Srvr="localhost";Ref="WIM_DU";')
def run(text, **p):
    q = c.NewObject('Запрос'); q.Текст = text
    for k, v in p.items(): q.УстановитьПараметр(k, v)
    r = q.Выполнить(); s = r.Выбрать(); n = r.Колонки.Количество(); out = []
    while s.Следующий(): out.append([str(s.Получить(j)) for j in range(n)])
    return out
