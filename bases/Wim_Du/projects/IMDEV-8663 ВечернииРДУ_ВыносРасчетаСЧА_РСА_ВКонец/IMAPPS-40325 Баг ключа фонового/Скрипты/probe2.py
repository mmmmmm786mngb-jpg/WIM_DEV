"""IMAPPS-40325: группы договоров ДУ, настройки вечерних операций, свободная дата."""
import os, sys
import pythoncom, win32com.client
sys.stdout.reconfigure(encoding='utf-8')
pythoncom.CoInitialize()
c = win32com.client.Dispatch('V83.COMConnector').Connect('Srvr="localhost";Ref="WIM_DU";')
def run(text, **p):
    q = c.NewObject('Запрос'); q.Текст = text
    for k, v in p.items(): q.УстановитьПараметр(k, v)
    r = q.Выполнить(); s = r.Выбрать(); n = r.Колонки.Количество(); out = []
    while s.Следующий(): out.append([str(s.Получить(j)) for j in range(n)])
    return out
for row in run('''ВЫБРАТЬ ПЕРВЫЕ 15 ПРЕДСТАВЛЕНИЕ(Д.Портфель) КАК П, ПРЕДСТАВЛЕНИЕ(Д.ТипКлиентаДУ) КАК Т, КОЛИЧЕСТВО(*) КАК К ИЗ Справочник.ДоговорДУ КАК Д
 ГДЕ НЕ Д.ПометкаУдаления СГРУППИРОВАТЬ ПО ПРЕДСТАВЛЕНИЕ(Д.Портфель), ПРЕДСТАВЛЕНИЕ(Д.ТипКлиентаДУ) УПОРЯДОЧИТЬ ПО К УБЫВ'''):
    print('ГРУППА', row)
print('Измерения/ресурсы НастройкиЗакрытияПериода:')
m = c.Метаданные.РегистрыСведений.НастройкиЗакрытияПериода
print([d.Имя for d in m.Измерения], [r.Имя for r in m.Ресурсы], m.ПериодичностьРегистраСведений)
for row in run('''ВЫБРАТЬ ПРЕДСТАВЛЕНИЕ(Н.ВидОперации.Родитель) КАК Гр, КОЛИЧЕСТВО(*) КАК К ИЗ РегистрСведений.НастройкиЗакрытияПериода КАК Н
 СГРУППИРОВАТЬ ПО ПРЕДСТАВЛЕНИЕ(Н.ВидОперации.Родитель)'''):
    print('НАСТР', row)
for row in run('''ВЫБРАТЬ В.Код КАК Код, В.Наименование КАК Н, В.Родитель.Код КАК Р, В.Отключить КАК О ИЗ Справочник.ВидыОперацийЗакрытияПериода КАК В
 ГДЕ В.Родитель.Код = "2. ""Вечерние"" операции"'''):
    print('ВЕЧ', row)
sys.stdout.flush(); os._exit(0)
