def main():
    target = sys.argv[1]
    if os.path.exists(os.path.join(target, OBJ)):
        shutil.rmtree(os.path.join(target, OBJ))
    os.makedirs(os.path.join(target, "Catalogs"), exist_ok=True)
    shutil.copytree(os.path.join(SRC, OBJ), os.path.join(target, OBJ))
    shutil.copy2(os.path.join(SRC, OBJ + ".xml"), os.path.join(target, OBJ + ".xml"))

    for rel, patch in ((MANAGER, patch_manager), (FORM_MODULE, patch_form)):
        path = os.path.join(target, rel)
        text, bom, crlf = read(path)
        write(path, patch(text), bom, crlf)
        print("Пропатчен", rel)


if __name__ == "__main__":
    main()
