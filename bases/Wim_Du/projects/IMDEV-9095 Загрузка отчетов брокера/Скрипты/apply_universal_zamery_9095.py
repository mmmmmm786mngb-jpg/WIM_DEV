#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Apply universal performance measurement block to IMDEV-9095 EPF."""

from pathlib import Path

PROJECT = Path(__file__).resolve().parents[1]
EPF_DIR = next((PROJECT / "Обработки").glob("внРаспределение*"))
INNER = next(EPF_DIR.glob("внРаспределение*"))
OBJ_PATH = INNER / "Ext" / "ObjectModule.bsl"
FORM_PATH = INNER / "Forms" / "Форма" / "Ext" / "Form" / "Module.bsl"

ZAMER_BLOCK = r"""

#Область IMDEV_9095_Замеры

// Описание: Возвращает общий модуль ОценкаПроизводительности, если он есть в конфигурации.
// Динамическое обращение по имени - EPF компилируется на базе без релиза IMDEV-8927.
//
// Возвращаемое значение:
// ОбщийМодуль - модуль оценки производительности или Неопределено
//
Функция МодульОценкиПроизводительности()
	
	ИмяМодуля = "ОценкаПроизводительности";
	
	Если Метаданные.ОбщиеМодули.Найти(ИмяМодуля) = Неопределено Тогда
		Возврат Неопределено;
	КонецЕсли;
	
	Возврат ОбщегоНазначения.ОбщийМодуль(ИмяМодуля);
	
КонецФункции

// Описание: Начинает замер ключевой операции, если подсистема оценки производительности доступна.
//
// Возвращаемое значение:
// Число - метка начала замера в миллисекундах или 0, если замер недоступен
//
Функция НачатьЗамерОперации() Экспорт
	
	МодульОценки = МодульОценкиПроизводительности();
	Если МодульОценки = Неопределено Тогда
		Возврат 0;
	КонецЕсли;
	
	Возврат МодульОценки.НачатьЗамерВремени();
	
КонецФункции

// Описание: Завершает замер ключевой операции, если замер был начат.
//
// Параметры:
// КлючеваяОперация - Строка - имя ключевой операции БСП
// ВремяНачала - Число - метка начала замера
// ВесЗамера - Число - вес замера (количество обработанных объектов)
// Комментарий - Строка, Неопределено - дополнительный комментарий
// ВыполненСОшибкой - Булево - признак завершения с ошибкой
//
Процедура ЗакончитьЗамерОперации(КлючеваяОперация, ВремяНачала, ВесЗамера = 1, Комментарий = Неопределено, ВыполненСОшибкой = Ложь) Экспорт
	
	Если ВремяНачала = 0 Тогда
		Возврат;
	КонецЕсли;
	
	МодульОценки = МодульОценкиПроизводительности();
	Если МодульОценки = Неопределено Тогда
		Возврат;
	КонецЕсли;
	
	МодульОценки.ЗакончитьЗамерВремени(КлючеваяОперация, ВремяНачала, ВесЗамера, Комментарий, ВыполненСОшибкой);
	
КонецПроцедуры

// Описание: Добавляет в комментарий замера скорость обработки (вес / время), об/с.
//
// Параметры:
// Вес - Число - количество обработанных объектов
// ВремяНачала - Число - метка начала замера в миллисекундах
//
// Возвращаемое значение:
// Строка - фрагмент комментария вида "; УдельныйВес=1.25 об/с"
//
Функция ДополнениеКомментарияУдельныйВес(Вес, ВремяНачала) Экспорт
	
	ДлительностьСек = (ТекущаяУниверсальнаяДатаВМиллисекундах() - ВремяНачала) / 1000;
	Скорость = ?(ДлительностьСек > 0, Вес / ДлительностьСек, 0);
	
	Возврат "; УдельныйВес=" + Формат(Скорость, "ЧЦ=10; ЧДЦ=2") + " об/с";
	
КонецФункции

// Описание: Формирует имя ключевой операции БСП для замера распределения доходов по ЦБ (РДУ).
//
// Параметры:
// ЭтапЗамера - Строка - этап замера (Заполнение, СозданиеОпераций)
//
// Возвращаемое значение:
// Строка - имя ключевой операции в формате ДУ.РаспределениеДоходов.<Этап>.внРаспределениеДоходовПоЦеннымБумагам
//
Функция ПолучитьИмяКлючевойОперацииЗамера(Знач ЭтапЗамера) Экспорт
	
	Возврат "ДУ.РаспределениеДоходов." + ЭтапЗамера + ".внРаспределениеДоходовПоЦеннымБумагам";
	
КонецФункции

#КонецОбласти
"""

NEW_FILL = """&НаСервере
Процедура ЗаполнитьВсёНаСервере()
	
	ТекОбъект = РеквизитФормыВЗначение("Объект");
	
	// IMDEV-9095 ++
	КлючеваяОперацияЗаполнение = ТекОбъект.ПолучитьИмяКлючевойОперацииЗамера("Заполнение");
	ВремяНачалаЗамераЗаполнение = ТекОбъект.НачатьЗамерОперации();
	// IMDEV-9095 --
	
	ТекОбъект.ЗаполнитьТаблицуНКД();
	ТекОбъект.ЗаполнитьТаблицуПогашение();
	ТекОбъект.ЗаполнитьТаблицуДивиденды();
	ЗначениеВРеквизитФормы(ТекОбъект, "Объект");
	
	// IMDEV-9095 ++
	Если ВремяНачалаЗамераЗаполнение > 0 Тогда
		СтрокНКД = ТекОбъект.Купон.Количество();
		СтрокПогашение = ТекОбъект.Погашение.Количество();
		СтрокДивиденды = ТекОбъект.Дивиденды.Количество();
		ВесЗамераЗаполнение = СтрокНКД + СтрокПогашение + СтрокДивиденды;
		ВесЗамераФинальный = ?(ВесЗамераЗаполнение > 0, ВесЗамераЗаполнение, 1);
		КомментарийЗамераЗаполнение = "Пул=" + ТекОбъект.Пул
			+ "; Период=" + Формат(ТекОбъект.Период, "ДФ=dd.MM.yyyy")
			+ "; СтрокНКД=" + СтрокНКД
			+ "; СтрокПогашение=" + СтрокПогашение
			+ "; СтрокДивиденды=" + СтрокДивиденды
			+ "; Отказ=Нет"
			+ ТекОбъект.ДополнениеКомментарияУдельныйВес(ВесЗамераФинальный, ВремяНачалаЗамераЗаполнение);
		ТекОбъект.ЗакончитьЗамерОперации(
			КлючеваяОперацияЗаполнение,
			ВремяНачалаЗамераЗаполнение,
			ВесЗамераФинальный,
			КомментарийЗамераЗаполнение,
			Ложь);
	КонецЕсли;
	// IMDEV-9095 --

КонецПроцедуры"""

NEW_CREATE = """&НаСервере
Процедура СоздатьВсёНаСервере(МассивСообщений)
	
	ТекОбъект = РеквизитФормыВЗначение("Объект");
	
	// IMDEV-9095 ++
	КлючеваяОперацияСоздание = ТекОбъект.ПолучитьИмяКлючевойОперацииЗамера("СозданиеОпераций");
	ВремяНачалаЗамераСоздание = ТекОбъект.НачатьЗамерОперации();
	ОтмНКД = 0;
	ОтмПогашение = 0;
	ОтмДивиденды = 0;
	Для Каждого Стр Из ТекОбъект.Купон Цикл
		Если Стр.Отм Тогда
			ОтмНКД = ОтмНКД + 1;
		КонецЕсли;
	КонецЦикла;
	Для Каждого Стр Из ТекОбъект.Погашение Цикл
		Если Стр.Отм Тогда
			ОтмПогашение = ОтмПогашение + 1;
		КонецЕсли;
	КонецЦикла;
	Для Каждого Стр Из ТекОбъект.Дивиденды Цикл
		Если Стр.Отм Тогда
			ОтмДивиденды = ОтмДивиденды + 1;
		КонецЕсли;
	КонецЦикла;
	ВесЗамераСоздание = ОтмНКД + ОтмПогашение + ОтмДивиденды;
	// IMDEV-9095 --
	
	ТекОбъект.СоздатьОперацииПоНКД(МассивСообщений);
	ТекОбъект.СоздатьОперацииПоПогашение(МассивСообщений);
	ТекОбъект.СоздатьОперацииПоДивидендам(МассивСообщений);
	ЗначениеВРеквизитФормы(ТекОбъект, "Объект");
	
	// IMDEV-9095 ++
	Если ВремяНачалаЗамераСоздание > 0 Тогда
		КоличествоОшибок = 0;
		КоличествоУспехов = 0;
		Для Каждого СообщениеЗамера Из МассивСообщений Цикл
			Если СтрНачинаетсяС(СообщениеЗамера, "Создана операция") Тогда
				КоличествоУспехов = КоличествоУспехов + 1;
			Иначе
				КоличествоОшибок = КоличествоОшибок + 1;
			КонецЕсли;
		КонецЦикла;
		ВесЗамераФинальный = ?(ВесЗамераСоздание > 0, ВесЗамераСоздание, 1);
		ОтказЗамера = КоличествоОшибок > 0;
		КомментарийЗамераСоздание = "Пул=" + ТекОбъект.Пул
			+ "; Период=" + Формат(ТекОбъект.Период, "ДФ=dd.MM.yyyy")
			+ "; ОтмНКД=" + ОтмНКД
			+ "; ОтмПогашение=" + ОтмПогашение
			+ "; ОтмДивиденды=" + ОтмДивиденды
			+ "; Успехов=" + КоличествоУспехов
			+ "; Ошибок=" + КоличествоОшибок
			+ "; Отказ=" + ?(ОтказЗамера, "Да", "Нет")
			+ ТекОбъект.ДополнениеКомментарияУдельныйВес(ВесЗамераФинальный, ВремяНачалаЗамераСоздание);
		ТекОбъект.ЗакончитьЗамерОперации(
			КлючеваяОперацияСоздание,
			ВремяНачалаЗамераСоздание,
			ВесЗамераФинальный,
			КомментарийЗамераСоздание,
			ОтказЗамера);
	КонецЕсли;
	// IMDEV-9095 --

КонецПроцедуры"""


def replace_procedure(text, proc_name, new_body):
    marker = f"&НаСервере\nПроцедура {proc_name}"
    start = text.find(marker)
    if start < 0:
        raise ValueError(f"Procedure not found: {proc_name}")
    end = text.find("КонецПроцедуры", start) + len("КонецПроцедуры")
    return text[:start] + new_body + text[end:]


def main():
    obj_text = OBJ_PATH.read_text(encoding="utf-8")
    if "IMDEV_9095_Замеры" not in obj_text:
        obj_text = obj_text.rstrip() + ZAMER_BLOCK + "\n"
        OBJ_PATH.write_text(obj_text, encoding="utf-8")
        print("ObjectModule: zamer block added")

    form_text = FORM_PATH.read_text(encoding="utf-8")
    form_text = replace_procedure(form_text, "ЗаполнитьВсёНаСервере()", NEW_FILL)
    form_text = replace_procedure(form_text, "СоздатьВсёНаСервере(МассивСообщений)", NEW_CREATE)

    region_start = form_text.find("#Область IMDEV_8927")
    if region_start >= 0:
        form_text = form_text[:region_start].rstrip() + "\n\n"

    FORM_PATH.write_text(form_text, encoding="utf-8")
    print("Form module updated")


if __name__ == "__main__":
    main()
