def replace_procedure(text, proc_name, new_body):
    marker = f"&НаСервере\nПроцедура {proc_name}"
    start = text.find(marker)
    if start < 0:
        raise ValueError(f"Procedure not found: {proc_name}")
    end = text.find("КонецПроцедуры", start) + len("КонецПроцедуры")
    return text[:start] + new_body + text[end:]


def main():
    text = FORM_PATH.read_text(encoding="utf-8")
    if text.startswith("\ufeff"):
        text = text[1:]
    if "КлючеваяОперацияЗаполнение" in text:
        print("OK - fill zamer already present")
        return
    text = replace_procedure(text, "ЗаполнитьВсёНаСервере()", NEW_FILL)
    FORM_PATH.write_text(text, encoding="utf-8")
    print("OK - fill zamer restored")


if __name__ == "__main__":
    main()
