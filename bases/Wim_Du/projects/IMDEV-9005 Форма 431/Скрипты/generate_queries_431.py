def build_query(ts_name: str, fields: list[str]) -> str:
    select_lines = ",\n\t".join(f"ТЧ.{f} КАК {f}" for f in fields)
    order_lines = ",\n\t".join(fields)
    return f"""// Tabular section: {ts_name}
// Parameter: &Документ (DocumentRef.{DOC_NAME})
// No LineNumber / НомерСтроки - stable compare by field values only

ВЫБРАТЬ
\t{select_lines}
ИЗ
\t{DOC_QUERY}.{ts_name} КАК ТЧ
ГДЕ
\tТЧ.Ссылка = &Документ
УПОРЯДОЧИТЬ ПО
\t{order_lines}
"""


def build_counts_query() -> str:
    parts = []
    for ts_name, _ in SECTIONS.values():
        parts.append(
            f"ВЫБРАТЬ\n"
            f"\t\"{ts_name}\" КАК ТабличнаяЧасть,\n"
            f"\tКОЛИЧЕСТВО(*) КАК КоличествоСтрок\n"
            f"ИЗ\n"
            f"\t{DOC_QUERY}.{ts_name} КАК ТЧ\n"
            f"ГДЕ\n"
            f"\tТЧ.Ссылка = &Документ"
        )
    body = "\n\nОБЪЕДИНИТЬ ВСЕ\n\n".join(parts)
    return f"""// Row counts for all tabular sections filled by external processor
// Parameter: &Документ (DocumentRef.{DOC_NAME})

{body}

УПОРЯДОЧИТЬ ПО
\tТабличнаяЧасть
"""


