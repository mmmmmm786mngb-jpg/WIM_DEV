#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Patch ObjectModule.bsl: pass batch params directly via background job args.

Root cause: temp storage written in one background session is not reliably
readable from another background session (worker), so СервисныеПараметры = Неопределено.
Fix: deliver input params through the serialized background job parameters
(ОбъектыНазначения[0] as a Structure); keep temp storage only for the result.
"""

import pathlib
import sys


def main() -> int:
    root = pathlib.Path(__file__).resolve().parents[1] / "Обраб"
    files = list(root.rglob("ObjectModule.bsl"))
    if not files:
        print("ERROR: ObjectModule.bsl not found")
        return 1

    path = files[0]
    text = path.read_text(encoding="utf-8")

    # --- 1. Orchestrator: input via job params instead of temp storage ---
    orch_old = (
        '\t\t// Постоянный адрес (владелец - УникальныйИдентификатор), чтобы значение пережило вызов\n'
        '\t\t// и было доступно из фонового сеанса по тому же адресу.\n'
        '\t\tАдресХранилища = ПоместитьВоВременноеХранилище(Неопределено, Новый УникальныйИдентификатор);\n'
        '\t\t\n'
        '\t\tПараметрыВыполненияПачки = Новый Структура;\n'
        '\t\tПараметрыВыполненияПачки.Вставить("Пачка",\t\t\t\tПачка);\n'
        '\t\tПараметрыВыполненияПачки.Вставить("НачалоПериода",\t\tОтчетОбъект.НачалоПериода);\n'
        '\t\tПараметрыВыполненияПачки.Вставить("КонецПериода",\t\tОтчетОбъект.КонецПериода);\n'
        '\t\tПараметрыВыполненияПачки.Вставить("УправляющаяКомпания",\tОтчетОбъект.УправляющаяКомпания);\n'
        '\t\tПараметрыВыполненияПачки.Вставить("Настройки",\t\t\tНастройки);\n'
        '\t\tПараметрыВыполненияПачки.Вставить("АдресХранилища",\t\tАдресХранилища);\n'
        '\t\t\n'
        '\t\t// Входные параметры пачки сохраняем до запуска - воркер прочитает по адресу из ОбъектыНазначения\n'
        '\t\tПоместитьВоВременноеХранилище(ПараметрыВыполненияПачки, АдресХранилища);\n'
        '\t\t\n'
        '\t\t// Для вида "ЗаполнениеОбъекта" БСП после команды обходит ОбъектыНазначения -\n'
        '\t\t// передаём пустой массив с адресом параметров (не Неопределено).\n'
        '\t\tОбъектыДляЗадания = Новый Массив;\n'
        '\t\tОбъектыДляЗадания.Добавить(АдресХранилища);\n'
    )

    orch_new = (
        '\t\t// IMDEV-9005 ++ адрес ТОЛЬКО для результата (UUID-время жизни, доступен между сеансами).\n'
        '\t\t// Реальное значение-заглушка гарантирует создание долгоживущей записи хранилища.\n'
        '\t\tАдресХранилища = ПоместитьВоВременноеХранилище(Новый Структура("Готово", Ложь), Новый УникальныйИдентификатор);\n'
        '\t\t\n'
        '\t\tПараметрыВыполненияПачки = Новый Структура;\n'
        '\t\tПараметрыВыполненияПачки.Вставить("Пачка",\t\t\t\tПачка);\n'
        '\t\tПараметрыВыполненияПачки.Вставить("НачалоПериода",\t\tОтчетОбъект.НачалоПериода);\n'
        '\t\tПараметрыВыполненияПачки.Вставить("КонецПериода",\t\tОтчетОбъект.КонецПериода);\n'
        '\t\tПараметрыВыполненияПачки.Вставить("УправляющаяКомпания",\tОтчетОбъект.УправляющаяКомпания);\n'
        '\t\tПараметрыВыполненияПачки.Вставить("Настройки",\t\t\tНастройки);\n'
        '\t\tПараметрыВыполненияПачки.Вставить("АдресХранилища",\t\tАдресХранилища);\n'
        '\t\t\n'
        '\t\t// Входные параметры передаём НАПРЯМУЮ через параметры фонового задания (платформа их\n'
        '\t\t// сериализует и доставит в фоновый сеанс). Временное хранилище между двумя фоновыми\n'
        '\t\t// сеансами для ВХОДА ненадёжно, поэтому используем его только для ОБРАТНОЙ передачи результата.\n'
        '\t\tОбъектыДляЗадания = Новый Массив;\n'
        '\t\tОбъектыДляЗадания.Добавить(ПараметрыВыполненияПачки);\n'
        '\t\t// IMDEV-9005 --\n'
    )

    if orch_old not in text:
        print("ERROR: orchestrator block not found")
        return 1
    text = text.replace(orch_old, orch_new, 1)

    # --- 2. Worker: accept Structure directly (fallback to address string) ---
    worker_old = (
        '\tСервисныеПараметры = Неопределено;\n'
        '\t\n'
        '\t// Путь для вида "ЗаполнениеОбъекта": адрес параметров в ОбъектыНазначения[0]\n'
        '\tЕсли ОбъектыНазначения <> Неопределено И ОбъектыНазначения.Количество() > 0 Тогда\n'
        '\t\tАдресПараметров = ОбъектыНазначения[0];\n'
        '\t\tЕсли ТипЗнч(АдресПараметров) = Тип("Строка") Тогда\n'
        '\t\t\tСервисныеПараметры = ПолучитьИзВременногоХранилища(АдресПараметров);\n'
        '\t\tКонецЕсли;\n'
        '\tКонецЕсли;\n'
    )

    worker_new = (
        '\tСервисныеПараметры = Неопределено;\n'
        '\t\n'
        '\t// IMDEV-9005 ++ параметры пачки приходят первым элементом ОбъектыНазначения:\n'
        '\t//   Структура - переданы напрямую через параметры фонового задания (надёжно);\n'
        '\t//   Строка    - адрес временного хранилища (резервный путь).\n'
        '\tЕсли ОбъектыНазначения <> Неопределено И ОбъектыНазначения.Количество() > 0 Тогда\n'
        '\t\tЭлементПараметров = ОбъектыНазначения[0];\n'
        '\t\tЕсли ТипЗнч(ЭлементПараметров) = Тип("Структура") Тогда\n'
        '\t\t\tСервисныеПараметры = ЭлементПараметров;\n'
        '\t\tИначеЕсли ТипЗнч(ЭлементПараметров) = Тип("Строка") Тогда\n'
        '\t\t\tСервисныеПараметры = ПолучитьИзВременногоХранилища(ЭлементПараметров);\n'
        '\t\tКонецЕсли;\n'
        '\tКонецЕсли;\n'
        '\t// IMDEV-9005 --\n'
    )

    if worker_old not in text:
        print("ERROR: worker block not found")
        return 1
    text = text.replace(worker_old, worker_new, 1)

    path.write_text(text, encoding="utf-8")
    print("OK patched:", path)
    return 0


if __name__ == "__main__":
    sys.exit(main())
