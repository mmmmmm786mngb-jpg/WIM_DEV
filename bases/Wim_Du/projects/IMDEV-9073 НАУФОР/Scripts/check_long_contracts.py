#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Proverka usloviya dogovora > 5 let dlya otcheta NAUFOR."""

import pythoncom
import win32com.client


def main():
    pythoncom.CoInitialize()
    try:
        com = win32com.client.Dispatch("V83.COMConnector")
        conn = com.Connect("Srvr='localhost';Ref='WIM_DU';")

        queries = [
            (
                "STRICT_GT_5_TERM",
                "ВЫБРАТЬ КОЛИЧЕСТВО(Д.Ссылка) КАК Кол "
                "ИЗ Справочник.ДоговорДУ КАК Д "
                "ГДЕ НЕ Д.ПометкаУдаления И Д.ДатаОкончания = ДАТАВРЕМЯ(1, 1, 1) "
                "И ((Д.СрокДействия > 0 И Д.СрокДействия <= 100 И Д.СрокДействия > 5) "
                "ИЛИ Д.СрокДействия > 1825 "
                "ИЛИ (Д.ДействуетДо <> ДАТАВРЕМЯ(1, 1, 1) И Д.ДатаНачала <> ДАТАВРЕМЯ(1, 1, 1) "
                "И ДОБАВИТЬКДАТЕ(Д.ДатаНачала, ГОД, 5) < Д.ДействуетДо))",
            ),
            (
                "TERM_EQ_5_YEARS",
                "ВЫБРАТЬ КОЛИЧЕСТВО(Д.Ссылка) КАК Кол "
                "ИЗ Справочник.ДоговорДУ КАК Д "
                "ГДЕ НЕ Д.ПометкаУдаления И Д.ДатаОкончания = ДАТАВРЕМЯ(1, 1, 1) "
                "И Д.СрокДействия = 5",
            ),
            (
                "TERM_EQ_1825_DAYS",
                "ВЫБРАТЬ КОЛИЧЕСТВО(Д.Ссылка) КАК Кол "
                "ИЗ Справочник.ДоговорДУ КАК Д "
                "ГДЕ НЕ Д.ПометкаУдаления И Д.ДатаОкончания = ДАТАВРЕМЯ(1, 1, 1) "
                "И Д.СрокДействия = 1825",
            ),
            (
                "ELAPSED_GT_5_YEARS",
                "ВЫБРАТЬ КОЛИЧЕСТВО(Д.Ссылка) КАК Кол "
                "ИЗ Справочник.ДоговорДУ КАК Д "
                "ГДЕ НЕ Д.ПометкаУдаления И Д.ДатаОкончания = ДАТАВРЕМЯ(1, 1, 1) "
                "И Д.ДатаНачала <> ДАТАВРЕМЯ(1, 1, 1) "
                "И ДОБАВИТЬКДАТЕ(Д.ДатаНачала, ГОД, 5) < ДАТАВРЕМЯ(2026, 3, 31)",
            ),
            (
                "TERM_GTE_5_OR_1825",
                "ВЫБРАТЬ КОЛИЧЕСТВО(Д.Ссылка) КАК Кол "
                "ИЗ Справочник.ДоговорДУ КАК Д "
                "ГДЕ НЕ Д.ПометкаУдаления И Д.ДатаОкончания = ДАТАВРЕМЯ(1, 1, 1) "
                "И ((Д.СрокДействия > 0 И Д.СрокДействия <= 100 И Д.СрокДействия >= 5) "
                "ИЛИ Д.СрокДействия >= 1825)",
            ),
        ]

        for label, text in queries:
            q = conn.NewObject("Запрос")
            q.Текст = text
            s = q.Выполнить().Выбрать()
            if s.Следующий():
                print(label, int(s.Кол))

        q_all = conn.NewObject("Запрос")
        q_all.Текст = "ВЫБРАТЬ КОЛИЧЕСТВО(*) КАК Кол ИЗ Справочник.ДоговорДУ КАК Д"
        s_all = q_all.Выполнить().Выбрать()
        s_all.Следующий()
        print("ALL_CONTRACTS", int(s_all.Кол))

        q = conn.NewObject("Запрос")
        q.Текст = (
            "ВЫБРАТЬ ПЕРВЫЕ 10\n"
            "    Д.Код,\n"
            "    Д.ДатаНачала,\n"
            "    Д.СрокДействия,\n"
            "    Д.ДействуетДо,\n"
            "    Д.ПролонгацияДоговора\n"
            "ИЗ\n"
            "    Справочник.ДоговорДУ КАК Д\n"
            "ГДЕ\n"
            "    НЕ Д.ПометкаУдаления\n"
            "    И Д.ДатаОкончания = ДАТАВРЕМЯ(1, 1, 1)\n"
            "    И ((Д.СрокДействия > 0 И Д.СрокДействия <= 100 И Д.СрокДействия > 5)\n"
            "        ИЛИ Д.СрокДействия > 1825\n"
            "        ИЛИ (Д.ДействуетДо <> ДАТАВРЕМЯ(1, 1, 1)\n"
            "            И Д.ДатаНачала <> ДАТАВРЕМЯ(1, 1, 1)\n"
            "            И ДОБАВИТЬКДАТЕ(Д.ДатаНачала, ГОД, 5) < Д.ДействуетДо))"
        )
        s = q.Выполнить().Выбрать()
        print("LONG_CONTRACTS_SAMPLE:")
        while s.Следующий():
            print(
                " ",
                s.Код,
                "start=",
                s.ДатаНачала,
                "term=",
                s.СрокДействия,
                "until=",
                s.ДействуетДо,
                "prol=",
                s.ПролонгацияДоговора,
            )

    finally:
        pythoncom.CoUninitialize()


if __name__ == "__main__":
    main()
