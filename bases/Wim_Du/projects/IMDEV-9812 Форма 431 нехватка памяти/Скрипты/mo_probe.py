import win32com.client

c = win32com.client.Dispatch("V83.COMConnector").Connect('Srvr="localhost";Ref="WIM_MO";')
q = c.NewObject("Запрос")
q.Текст = """
ВЫБРАТЬ
    СМ.Стратегия.КодСтратегии КАК Код,
    СМ.Стратегия.Наименование КАК Наим,
    СМ.Стратегия.Родитель.КодСтратегии КАК КодРодителя,
    КОЛИЧЕСТВО(РАЗЛИЧНЫЕ СМ.Владелец) КАК Мандатов,
    КОЛИЧЕСТВО(*) КАК Счетов
ИЗ Справочник.СчетаМандатов КАК СМ
ГДЕ НЕ СМ.ПометкаУдаления
СГРУППИРОВАТЬ ПО СМ.Стратегия.КодСтратегии, СМ.Стратегия.Наименование, СМ.Стратегия.Родитель.КодСтратегии
УПОРЯДОЧИТЬ ПО Мандатов УБЫВ"""
s = q.Выполнить().Выбрать()
n = 0
while s.Следующий() and n < 25:
    n += 1
    print(s.Код, "|", s.Наим, "| родитель", s.КодРодителя, "| мандатов", s.Мандатов, "| счетов", s.Счетов)
q.Текст = "ВЫБРАТЬ КОЛИЧЕСТВО(*) КАК К ИЗ РегистрНакопления.ВводыВыводыВДУ"
s = q.Выполнить().Выбрать(); s.Следующий(); print("ВводыВыводыВДУ записей", s.К)
