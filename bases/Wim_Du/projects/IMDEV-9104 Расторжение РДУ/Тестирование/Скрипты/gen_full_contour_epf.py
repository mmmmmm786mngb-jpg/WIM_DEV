def new_uuid() -> str:
    return str(uuid.uuid4())


def copy_tree() -> Path:
    if DST_ROOT.exists():
        shutil.rmtree(DST_ROOT)
    DST_ROOT.mkdir(parents=True)
    src_obj = SRC_ROOT / SRC_NAME_FOLDER
    dst_obj = DST_ROOT / DST_NAME
    shutil.copytree(src_obj, dst_obj)
    # root xml
    src_xml = SRC_ROOT / f"{SRC_NAME_FOLDER}.xml"
    # production root xml is named after folder
    if not src_xml.exists():
        src_xml = SRC_ROOT / f"{SRC_META_NAME}.xml"
    # actual file from listing:
    candidates = list(SRC_ROOT.glob("*.xml"))
    if not candidates:
        raise FileNotFoundError("production root xml not found")
    src_xml = candidates[0]
    dst_xml = DST_ROOT / f"{DST_NAME}.xml"
    shutil.copy2(src_xml, dst_xml)
    return dst_obj


