#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""v1.2b: Сбросить(,,,ПрерыватьКонтур); date writes do not abort contour."""

from pathlib import Path

p = Path(__file__).resolve().parents[1] / (
    "внТестСравнениеПолныйКонтурP2_epf/внТестСравнениеПолныйКонтурP2/Ext/ObjectModule.bsl"
)
text = p.read_text(encoding="utf-8")

old = """Процедура СброситьИспорченнуюТранзакциюОтката(КонтекстОшибки = \"\")
\t
\tЕсли ОткатыватьТранзакцию <> Истина Тогда
\t\tВозврат;
\tКонецЕсли;
\tЕсли Не ТранзакцияАктивна() Тогда
\t\tНачатьТранзакцию();
\t\tВозврат;
\tКонецЕсли;
\t
\tОтменитьТранзакцию();
\tНачатьТранзакцию();
\t
\tКонтурПрерванИзЗаСбросаТранзакции = Истина;
\tТекстПоследнегоСбросаТранзакции = КонтекстОшибки;
\t
\tЗаписьЖурналаРегистрации(
\t\t\"IMDEV-9104.СравнениеПолныйP2\",
\t\tУровеньЖурналаРегистрации.Предупреждение,,,
\t\t\"Транзакция отката перезапущена; контур будет прерван\"
\t\t\t+ ?(ПустаяСтрока(КонтекстОшибки), \"\", \": \" + КонтекстОшибки));
\t
КонецПроцедуры"""

new = """Процедура СброситьИспорченнуюТранзакциюОтката(КонтекстОшибки = \"\", ПрерыватьКонтур = Истина)
\t
\tЕсли ОткатыватьТранзакцию <> Истина Тогда
\t\tВозврат;
\tКонецЕсли;
\tЕсли Не ТранзакцияАктивна() Тогда
\t\tНачатьТранзакцию();
\t\tВозврат;
\tКонецЕсли;
\t
\tОтменитьТранзакцию();
\tНачатьТранзакцию();
\t
\tЕсли ПрерыватьКонтур = Истина Тогда
\t\tКонтурПрерванИзЗаСбросаТранзакции = Истина;
\t\tТекстПоследнегоСбросаТранзакции = КонтекстОшибки;
\tКонецЕсли;
\t
\tЗаписьЖурналаРегистрации(
\t\t\"IMDEV-9104.СравнениеПолныйP2\",
\t\tУровеньЖурналаРегистрации.Предупреждение,,,
\t\t\"Транзакция отката перезапущена\"
\t\t\t+ ?(ПрерыватьКонтур = Истина, \"; контур будет прерван\", \" (без прерывания контура)\")
\t\t\t+ ?(ПустаяСтрока(КонтекстОшибки), \"\", \": \" + КонтекстОшибки));
\t
КонецПроцедуры"""

if old not in text:
    raise SystemExit("reset proc not found")
text = text.replace(old, new, 1)

# date write: do not abort contour on retry reset
old2 = """\t\t\tЕсли ОткатыватьТранзакцию = Истина Тогда
\t\t\t\t// После ошибки Записать транзакция \"испорчена\" - без сброса дальше любой Записать падает
\t\t\t\tСброситьИспорченнуюТранзакциюОтката(
\t\t\t\t\t\"УстановитьДатуРасторжения/\" + Формат(НомерПопытки, \"ЧГ=0\") + \": \" + ТекстОшибкиЗаписи);
\t\t\tКонецЕсли;"""

new2 = """\t\t\tЕсли ОткатыватьТранзакцию = Истина Тогда
\t\t\t\t// После ошибки Записать транзакция \"испорчена\" - без сброса дальше любой Записать падает
\t\t\t\t// ПрерыватьКонтур=Ложь: retry в РЗ, иначе весь Обработка будет пропущен
\t\t\t\tСброситьИспорченнуюТранзакциюОтката(
\t\t\t\t\t\"УстановитьДатуРасторжения/\" + Формат(НомерПопытки, \"ЧГ=0\") + \": \" + ТекстОшибкиЗаписи,
\t\t\t\t\tЛожь);
\t\t\tКонецЕсли;"""

if old2 not in text:
    raise SystemExit("date write reset not found")
text = text.replace(old2, new2, 1)

# date close: keep interrupt (during Обработка)
old3 = """\t\t\tЕсли ОткатыватьТранзакцию = Истина Тогда
\t\t\t\tСброситьИспорченнуюТранзакциюОтката(
\t\t\t\t\t\"УстановитьДатуЗакрытия/\" + Формат(НомерПопытки, \"ЧГ=0\") + \": \" + ТекстОшибкиЗаписи);
\t\t\tКонецЕсли;"""

new3 = """\t\t\tЕсли ОткатыватьТранзакцию = Истина Тогда
\t\t\t\tСброситьИспорченнуюТранзакциюОтката(
\t\t\t\t\t\"УстановитьДатуЗакрытия/\" + Формат(НомерПопытки, \"ЧГ=0\") + \": \" + ТекстОшибкиЗаписи,
\t\t\t\t\tИстина);
\t\t\tКонецЕсли;"""

if old3 not in text:
    raise SystemExit("date close reset not found")
text = text.replace(old3, new3, 1)

# bank account during RZ - no interrupt
text2 = text.replace(
    'СброситьИспорченнуюТранзакциюОтката("БанковскийСчет: " + ТекстОшибки);',
    'СброситьИспорченнуюТранзакциюОтката("БанковскийСчет: " + ТекстОшибки, Ложь);',
    1,
)
if text2 == text:
    raise SystemExit("bank reset not found")
text = text2

# ПоручениеПоДС during RZ mostly - no interrupt to allow Обработка; if happens mid-Обработка
# refs may die - УчестьНДФЛ is now safe. Still set interrupt for PP/NDFL/etc.
# Leave ПоручениеПоДС as default interrupt=True? During RZ it would skip Обработка.
# Better Ложь for ПоручениеПоДС - УчестьНДФЛ hardened.
text2 = text.replace(
    'СброситьИспорченнуюТранзакциюОтката("ПоручениеПоДС: " + ТекстОшибки);',
    'СброситьИспорченнуюТранзакциюОтката("ПоручениеПоДС: " + ТекстОшибки, Ложь);',
    1,
)
if text2 == text:
    raise SystemExit("poruchenie reset not found")
text = text2

p.write_text(text, encoding="utf-8")
print("OK v1.2b")
