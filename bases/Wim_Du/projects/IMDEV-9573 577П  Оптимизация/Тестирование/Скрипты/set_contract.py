# Добавляет в ДоговораДУ документа первый договор ДУ (у договоров dev-базы УК пустая -> "по другой УК").
import sys, os
sys.stdout.reconfigure(encoding="utf-8")
import stand
c = stand.connect()
o = stand.doc_by_number(c, sys.argv[1]).ПолучитьОбъект()
t = stand.query(c, "ВЫБРАТЬ ПЕРВЫЕ 1 Д.Ссылка КАК Ссылка ИЗ Справочник.ДоговорДУ КАК Д УПОРЯДОЧИТЬ ПО Д.Ссылка")
o.ДоговораДУ.Очистить()
if len(sys.argv) < 3:
    o.ДоговораДУ.Добавить().ДоговорДУ = t.Получить(0).Ссылка
o.ОбменДанными.Загрузка = True
o.Записать()
print("ДоговораДУ:", o.ДоговораДУ.Количество(), c.String(t.Получить(0).Ссылка), "Раздел7:", o.Раздел7.Количество())
sys.stdout.flush(); os._exit(0)
