# -*- coding: utf-8 -*-
"""Исходники тестовой обработки T9573_СтараяВыгрузкаCSV: серверный алгоритм прежней выгрузки CSV
(модуль формы ФормаДляФормированияCSV обработки СформироватьВыгрузкуCSV) без изменений, кроме
источника ссылки на документ и выдачи файла вместо временного хранилища. Нужна как эталон для
побайтного сравнения с потоковой выгрузкой. xlsx не формируется: на CSV не влияет.
"""
import os
import re
import uuid

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, "..", ".."))
SRC = os.path.join(ROOT, "src", "СформироватьВыгрузкуCSV", "Forms", "ФормаДляФормированияCSV", "Ext", "Form", "Module.bsl")
OUT = os.path.join(ROOT, "Тестирование", "Обработки")
NAME = "T9573_СтараяВыгрузкаCSV"

NAMES = ["СформироватьСохранитьТДПоРазделу", "СопроводительнаяИнформация", "СкорректироватьПредставлениеИПорядокПолей",
         "УстановитьОформление", "ЕстьДанные", "ГодОтчета", "СтруктураРазделовДляВыгрузки"] + \
        [f"СписокПредставленийРаздел{n}" for n in range(1, 12)]


def extract(text, name):
    m = re.search(r"^(Процедура|Функция) " + name + r"\(.*?^Конец(Процедуры|Функции)", text, re.S | re.M)
    if not m:
        raise SystemExit("нет метода " + name)
    return m.group(0)


def main():
    text = open(SRC, encoding="utf-8-sig").read().replace("\r\n", "\n")
    parts = []
    for name in NAMES:
        body = extract(text, name).replace("Объект.ДокументОтчета", "ДокументОтчета")
        if name == "СформироватьСохранитьТДПоРазделу":
            body = re.sub(r"\tИмяВременногоФайлаXLSX = .*?УникальныйИдентификатор\);\n", "", body, flags=re.S)
            tail = re.search(r"\tОбъект\.АдресХранилищаФайлаCSV.*?УдалитьФайлы\(ИмяВременногоФайлаXLSX\);\n", body, re.S)
            body = body[:tail.start()] + "\tВозврат ИмяВременногоФайла;\n" + body[tail.end():]
            body = body.replace("Процедура СформироватьСохранитьТДПоРазделу", "Функция СформироватьСохранитьТДПоРазделу", 1)
            body = re.sub(r"КонецПроцедуры\s*$", "КонецФункции", body)
            if "XLSX" in body or "АдресХранилища" in body:
                raise SystemExit("не вырезан xlsx или хранилище")
        parts.append(body)

    head = '''// Тестовая обработка IMDEV-9573, не для поставки.
// Серверный алгоритм прежней выгрузки CSV 577-П без изменений: эталон для сравнения с потоковой выгрузкой.

Перем ДокументОтчета;

// Выгружает R1-R11.csv и sr_sved_purcb.csv прежним алгоритмом в каталог сервера.
//
// Параметры:
//  Ссылка - ДокументСсылка.РО_XBRL6_1_ОтчетПоВнутреннемуУчету_577П - документ
//  Каталог - Строка - каталог с завершающим разделителем
//
// Возвращаемое значение:
//  Строка - время по разделам, мс
//
Функция Выгрузить(Ссылка, Каталог) Экспорт

\tДокументОтчета = Ссылка;
\tВремя = Новый Массив;

\tРазделыДляВыгрузки = СтруктураРазделовДляВыгрузки();
\tДля каждого Раздел из РазделыДляВыгрузки Цикл
\t\tНачало = ТекущаяУниверсальнаяДатаВМиллисекундах();
\t\tИмяВременногоФайла = СформироватьСохранитьТДПоРазделу(Раздел.Значение);
\t\tКопироватьФайл(ИмяВременногоФайла, Каталог + Раздел.Ключ + ".csv");
\t\tУдалитьФайлы(ИмяВременногоФайла);
\t\tВремя.Добавить(Раздел.Ключ + " " + Формат(ТекущаяУниверсальнаяДатаВМиллисекундах() - Начало, "ЧГ=0"));
\tКонецЦикла;

\tДанныеСопроводительнойИнформации = СопроводительнаяИнформация();

\tДанныеCSV = Новый ЗаписьТекста(Каталог + "sr_sved_purcb.csv", КодировкаТекста.UTF8);

\tМассивЗаголовков = Новый Массив;
\tМассивДанных = Новый Массив;

\tДля Каждого Колонка Из ДанныеСопроводительнойИнформации Цикл
\t\tМассивЗаголовков.Добавить(Колонка.Ключ);
\t\tМассивДанных.Добавить(Колонка.Значение);
\tКонецЦикла;
\tСтрокаЗаголовков = СтрСоединить(МассивЗаголовков, "|");
\tСтрокаЗначений = СтрСоединить(МассивДанных, "|");
\tДанныеCSV.ЗаписатьСтроку(СтрокаЗаголовков);
\tДанныеCSV.ЗаписатьСтроку(СтрокаЗначений);
\tДанныеCSV.Закрыть();

\tВозврат СтрСоединить(Время, Символы.ПС);

КонецФункции

'''
    module = head + "\n\n".join(parts) + "\n"
    ext = os.path.join(OUT, NAME, "Ext")
    os.makedirs(ext, exist_ok=True)
    with open(os.path.join(ext, "ObjectModule.bsl"), "w", encoding="utf-8-sig", newline="\r\n") as f:
        f.write(module)

    tpl = open(os.path.join(ROOT, "src", "СформироватьВыгрузкуCSVПоток.xml"), encoding="utf-8-sig").read()
    tpl = re.sub(r"\s*<Attribute uuid.*?</Attribute>", "", tpl, flags=re.S)
    tpl = re.sub(r"\s*<Form>.*?</Form>", "", tpl)
    tpl = tpl.replace("<ChildObjects>\n\t\t</ChildObjects>", "<ChildObjects/>")
    tpl = re.sub(r"<DefaultForm>.*?</DefaultForm>", "<DefaultForm/>", tpl)
    tpl = tpl.replace("СформироватьВыгрузкуCSVПоток", NAME).replace("Выгрузка CSV 577-П (поток)", "Тест: прежняя выгрузка CSV 577-П")
    for old in set(re.findall(r"[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}", tpl)):
        if old == "c3831ec8-d8d5-4f93-8a22-f9bfae07327f":
            continue
        tpl = tpl.replace(old, str(uuid.uuid4()))
    with open(os.path.join(OUT, NAME + ".xml"), "w", encoding="utf-8") as f:
        f.write(tpl)
    print("ok", os.path.join(OUT, NAME + ".xml"), len(module.splitlines()), "строк модуля")


if __name__ == "__main__":
    main()
