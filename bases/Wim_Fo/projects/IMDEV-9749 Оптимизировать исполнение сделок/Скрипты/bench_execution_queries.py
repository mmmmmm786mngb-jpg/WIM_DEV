def log(lines, text):
    lines.append(text)
    safe = text.encode("ascii", "replace").decode("ascii")
    print(safe, flush=True)


def num(value):
    if value is None:
        return None
    try:
        return float(value)
    except (TypeError, ValueError):
        return None


def median(samples):
    return statistics.median(samples) if samples else None


def fmt_ms(samples):
    if not samples:
        return "-"
    return "медиана %.1f мс, замеры %s" % (
        median(samples),
        ", ".join("%.1f" % item for item in samples),
    )


def fmt_row(row):
    if not row:
        return "пусто"
    parts = []
    for key, value in row.items():
        number = num(value)
        if number is None:
            parts.append("%s=NULL" % key)
        elif abs(number - round(number)) < 1e-6:
            parts.append("%s=%s" % (key, int(round(number))))
        else:
            parts.append("%s=%.4f" % (key, number))
    return ", ".join(parts)


def same_metrics(left, right, fields):
    if not left or not right:
        return False
    for field in fields:
        a = num(left.get(field))
        b = num(right.get(field))
        if a is None and b is None:
            continue
        if a is None or b is None or abs(a - b) > 0.001:
            return False
    return True


def timed(conn, text, params, repeats=3):
    stand.query(conn, text, params)
    samples = []
    rows = None
    for _ in range(repeats):
        started = time.perf_counter()
        rows = stand.query(conn, text, params)
        samples.append((time.perf_counter() - started) * 1000.0)
    return samples, rows


def ref_id(conn, ref):
    try:
        if ref is None:
            return ""
        empty = getattr(ref, "Пустая", None)
        if empty is not None and empty():
            return ""
        return conn.String(ref.УникальныйИдентификатор())
    except Exception:
        return ""


def unique_refs(conn, rows, field):
    found = []
    seen = set()
    for row in rows:
        ref = row.get(field)
        ident = ref_id(conn, ref)
        if not ident or ident in seen:
            continue
        seen.add(ident)
        found.append(ref)
    return found


def call_flag(conn, module_name, method_name):
    module = getattr(conn, module_name, None)
    if module is None:
        return None
    method = getattr(module, method_name, None)
    if method is None:
        return None
    return bool(method())


