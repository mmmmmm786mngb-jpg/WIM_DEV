function p(text, opts = {}) {
  const runs = (Array.isArray(text) ? text : [text]).map((t) =>
    typeof t === "string" ? new TextRun({ text: t, font: FONT, size: 22 }) : new TextRun({ font: FONT, size: 22, ...t }));
  return new Paragraph({ children: runs, spacing: { after: 100, line: 276 }, ...opts });
}
function h(text) {
  return new Paragraph({ heading: HeadingLevel.HEADING_1, children: [new TextRun({ text, font: FONT })], spacing: { before: 240, after: 120 } });
}
function bullet(text) {
  return p(text, { numbering: { reference: "bullets", level: 0 }, spacing: { after: 60, line: 276 } });
}
function num(text, ref) {
  return p(text, { numbering: { reference: ref, level: 0 }, spacing: { after: 60, line: 276 } });
}
function cell(text, width, opts = {}) {
  return new TableCell({
    borders, width: { size: width, type: WidthType.DXA },
    shading: opts.head ? { fill: "E6EDF5", type: ShadingType.CLEAR, color: "auto" }
      : opts.fill ? { fill: opts.fill, type: ShadingType.CLEAR, color: "auto" } : undefined,
    margins: { top: 60, bottom: 60, left: 100, right: 100 },
    children: [new Paragraph({
      alignment: opts.right ? AlignmentType.RIGHT : AlignmentType.LEFT,
      children: [new TextRun({ text, font: FONT, size: 20, bold: !!(opts.head || opts.bold) })],
    })],
  });
}
// Последний элемент строки может быть объектом { fill } - заливка строки (или столбца fillCol).
function table(widths, rows, { rightCols = [], fillCol = -1 } = {}) {
  return new Table({
    width: { size: widths.reduce((a, b) => a + b, 0), type: WidthType.DXA },
    columnWidths: widths,
    rows: rows.map((r, i) => {
      const hasMeta = typeof r[r.length - 1] === "object";
      const meta = hasMeta ? r[r.length - 1] : {};
      const texts = hasMeta ? r.slice(0, -1) : r;
      return new TableRow({
        tableHeader: i === 0,
        children: texts.map((t, j) => cell(String(t), widths[j], {
          head: i === 0, right: i > 0 && rightCols.includes(j),
          fill: i > 0 && (fillCol < 0 || j === fillCol) ? meta.fill : undefined,
        })),
      });
    }),
  });
}

