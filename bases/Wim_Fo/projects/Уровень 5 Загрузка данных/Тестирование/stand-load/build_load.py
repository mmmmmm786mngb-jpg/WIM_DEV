PATCHERS = {
    "ЗагрузкаДопРеквизитаTCRIS": patch_tcris,
    "внЗагрузкаКотировокММВБ": patch_mmvb,
    "внЗагрузкаИндексовФО": patch_indexes,
}


def main():
    os.makedirs(LOAD, exist_ok=True)
    os.makedirs(BUILD, exist_ok=True)
    for name, folder in PROCESSORS.items():
        src = os.path.join(ORIG, folder)
        dst = os.path.join(LOAD, folder)
        if os.path.exists(dst):
            shutil.rmtree(dst)
        shutil.copytree(src, dst)
        module = os.path.join(dst, name, "Ext", "ObjectModule.bsl")
        with open(module, encoding="utf-8-sig") as handle:
            text = handle.read()
        text = PATCHERS[name](text)
        with open(module, "w", encoding="utf-8-sig", newline="") as handle:
            handle.write(text)
        print("patched", name)

    if "--no-epf" in sys.argv:
        return
    db = sc.registry_db("wim_fo")
    for name, folder in PROCESSORS.items():
        xml = os.path.join(LOAD, folder, name + ".xml")
        out = os.path.join(BUILD, name + ".epf")
        cmd = [
            "powershell", "-NoProfile", "-ExecutionPolicy", "Bypass", "-File", BUILD_SCRIPT,
            "-SourceFile", xml, "-OutputFile", out,
            "-InfoBaseServer", db["server"], "-InfoBaseRef", db["ref"],
            "-UserName", db.get("user", ""), "-Password", db.get("password", ""),
            "-Checks", "off",
        ]
        result = subprocess.run(cmd, capture_output=True, text=True, encoding="utf-8", errors="replace")
        ok = os.path.exists(out) and "successfully" in (result.stdout or "")
        print("build", name, "OK" if ok else "FAIL")
        if not ok:
            print((result.stdout or "")[-1500:])
            print((result.stderr or "")[-500:])
            raise SystemExit(1)


if __name__ == "__main__":
    main()
