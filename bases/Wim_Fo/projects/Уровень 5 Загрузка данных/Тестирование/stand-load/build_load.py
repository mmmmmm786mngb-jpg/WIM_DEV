def insert_additions(text, additions):
    """Вставка функций перед последним #КонецОбласти: после него - операторы тела модуля."""
    marker = "#КонецОбласти"
    pos = text.rfind(marker)
    if pos < 0:
        return text + additions
    return text[:pos] + additions + "\n" + text[pos:]


def patch(text, old, new, label, count=1):
    found = text.count(old)
    if found < count:
        raise SystemExit("ANCHOR NOT FOUND (%s): %r" % (label, old[:80]))
    return text.replace(old, new, count)


