def page(title, body):
    return ("<!DOCTYPE html>\n<html lang=\"ru\">\n<head>\n<meta charset=\"utf-8\">\n"
            "<title>%s</title>\n<style>%s</style>\n</head>\n<body>\n%s\n</body>\n</html>\n"
            % (title, STYLE, body))


def table(headers, rows, num_cols):
    parts = ["<table>", "<tr>" + "".join(
        "<th%s>%s</th>" % (" class=\"num\"" if i in num_cols else "", h)
        for i, h in enumerate(headers)) + "</tr>"]
    for row in rows:
        parts.append("<tr>" + "".join(
            "<td%s>%s</td>" % (" class=\"num\"" if i in num_cols else "", c)
            for i, c in enumerate(row)) + "</tr>")
    parts.append("</table>")
    return "\n".join(parts)


