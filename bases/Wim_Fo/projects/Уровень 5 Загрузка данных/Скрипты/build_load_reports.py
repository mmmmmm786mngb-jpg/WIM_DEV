def build_report(op):
    body = ["<h1>Отчет о нагрузочном тестировании: %s</h1>" % op["slug"],
            "<p class=\"muted\">Нагрузочный стенд, разработческие базы, 14.11.2026</p>",
            "<h2>Что проверялось</h2>", "<p>%s</p>" % op["intro"],
            "<p><b>Объем прогона:</b> %s</p>" % op["volume"],
            "<h2>Результаты стенда</h2>",
            table(["Шаг", "Время, с", "Доля / на единицу"],
                  op["rows"], {1, 2})]
    if op["prod"]:
        body += ["<h2>Профиль рабочей базы за 16.10-02.11.2026 (среднее на запуск)</h2>",
                 table(["Шаг", "Розница, с", "Обычный ФО, с"], op["prod"], {1, 2})]
    else:
        body += ["<div class=\"note warn\">На рабочей базе эта операция пока не измеряется: ключи замера "
                 "появляются в конфигурации 1.4.10. Стендовые числа - первые по операции.</div>"]
    body += ["<h2>Выводы</h2>", "<ul>"]
    body += ["<li>%s</li>" % f for f in op["findings"]]
    body += ["</ul>", "<div class=\"note\">%s</div>" % REPORT_NOTE]
    return page("Нагрузочное тестирование - %s" % op["slug"], "\n".join(body))


def build_recs(op):
    body = ["<h1>Рекомендации по доработке: %s</h1>" % op["slug"],
            "<p class=\"muted\">По итогам нагрузочного тестирования 14.11.2026. Три главных предложения "
            "в порядке приоритета.</p>"]
    for number, (title, text, effect, complexity) in enumerate(op["recs"], 1):
        body.append("<div class=\"rec\"><h3>%d. %s</h3><p>%s</p>"
                    "<p class=\"meta\"><b>Ожидаемый эффект:</b> %s.<br>"
                    "<b>Сложность:</b> %s</p></div>" % (number, title, text, effect, complexity))
    return page("Рекомендации - %s" % op["slug"], "\n".join(body))


def main():
    os.makedirs(DOCS, exist_ok=True)
    for op in OPS:
        report = os.path.join(DOCS, "Отчет о нагрузочном тестировании - %s.html" % op["slug"])
        recs = os.path.join(DOCS, "Рекомендации - %s.html" % op["slug"])
        io.open(report, "w", encoding="utf-8").write(build_report(op))
        io.open(recs, "w", encoding="utf-8").write(build_recs(op))
        print("written:", os.path.basename(report))
        print("written:", os.path.basename(recs))


if __name__ == "__main__":
    main()
