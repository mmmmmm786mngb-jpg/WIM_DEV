def show(fo, title, text, params=None):
    print("---", title)
    try:
        rows = query(fo, text, params)
    except Exception as error:  # noqa: BLE001 - осмотр продолжается при ошибке одного запроса
        print("  ошибка:", str(error)[:300])
        return []
    for r in rows[:40]:
        print("  ", {k: fo.String(v) if not isinstance(v, (str, int, float, bool)) and v is not None else v
                     for k, v in r.items()})
    if len(rows) > 40:
        print(f"   ... строк {len(rows)}")
    return rows


