function p(text, opts = {}) {
  const runs = (Array.isArray(text) ? text : [text]).map((t) =>
    typeof t === "string" ? new TextRun({ text: t, font: FONT, size: 21 }) : new TextRun({ font: FONT, size: 21, ...t }));
  return new Paragraph({ children: runs, spacing: { after: 100, line: 276 }, ...opts });
}
function h(text, level = HeadingLevel.HEADING_1) {
  return new Paragraph({ heading: level, children: [new TextRun({ text, font: FONT })], spacing: { before: 220, after: 110 } });
}
function bullet(text) {
  return p(text, { numbering: { reference: "bullets", level: 0 }, spacing: { after: 50, line: 276 } });
}
function cellParas(text, head) {
  return String(text).split("\n").map((line) => new Paragraph({
    spacing: { after: 30 },
    children: [new TextRun({ text: line, font: FONT, size: 19, bold: head })],
  }));
}
function table(widths, rows, fills = {}) {
  return new Table({
    width: { size: widths.reduce((a, b) => a + b, 0), type: WidthType.DXA },
    columnWidths: widths,
    rows: rows.map((r, i) => new TableRow({
      tableHeader: i === 0, cantSplit: true,
      children: r.map((t, j) => new TableCell({
        borders, width: { size: widths[j], type: WidthType.DXA },
        shading: i === 0 ? { fill: "E6EDF5", type: ShadingType.CLEAR, color: "auto" }
          : fills[i] ? { fill: fills[i], type: ShadingType.CLEAR, color: "auto" } : undefined,
        margins: { top: 50, bottom: 50, left: 90, right: 90 },
        children: cellParas(t, i === 0),
      })),
    })),
  });
}

