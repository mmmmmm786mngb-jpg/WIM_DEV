# -*- coding: utf-8 -*-
"""Строит версию 1.20 обработки внЗагрузкаДепозитовИзВнешнихИсточников (каталог ОПТИМИЗИРОВАНО/src) из исходника 1.19
по постановке IMDEV-9742: в базе ФО Розница (RETAIL в константе ЗаголовокСистемы) загрузка депозитов не выполняется.
Кодировка (UTF-8 с BOM) и концы строк CRLF исходника сохраняются.

    python patch_1_20.py
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
TASK = os.path.dirname(HERE)
MODULE = os.path.join(TASK, "ОПТИМИЗИРОВАНО", "src", "внЗагрузкаДепозитовИзВнешнихИсточников", "Ext",
                      "ObjectModule.bsl")
MARK = "// IMDEV-9742: "


def block(indent, rows):
    return "".join("\t" * (indent + extra) + text + "\n" for extra, text in rows)


RETURN_IN_COMMAND = block(1, [
    (0, MARK + "в базе розницы загрузка не выполняется - депозитов у розничных клиентов нет"),
    (0, 'Если ИдентификаторКоманды = "ФоновоеВыполнение" И ЭтоБазаРозницы() Тогда'),
    (1, 'ЗаписьЖурналаРегистрации("ЗагрузкаДепозитов", УровеньЖурналаРегистрации.Информация, , ,'),
    (2, '"База розницы: загрузка депозитов не выполняется");'),
    (1, "Возврат;"),
    (0, "КонецЕсли;"),
    (0, ""),
])

RETURN_WITH_LOG = block(1, [
    (0, MARK + "в базе розницы источники депозитов не вызываются"),
    (0, "Если ЭтоБазаРозницы() Тогда"),
    (1, "Лог = Новый Массив;"),
    (1, "Возврат;"),
    (0, "КонецЕсли;"),
    (0, ""),
])

RETURN_PLAIN = block(1, [
    (0, MARK + "в базе розницы источники депозитов не вызываются"),
    (0, "Если ЭтоБазаРозницы() Тогда"),
    (1, "Возврат;"),
    (0, "КонецЕсли;"),
    (0, ""),
])

NEW_REGION = "\n".join([
    "#Область ПризнакБазыРозницы",
    "",
    "// IMDEV-9742",
    "//",
    "// Определяет, что текущая база - Фронт-офис Розница: в константе ЗаголовокСистемы розничной базы есть текст RETAIL.",
    "// В базе розницы загрузка депозитов не выполняется: депозитов у розничных клиентов нет.",
    "//",
    "// Возвращаемое значение:",
    "//  Булево - Истина для базы розницы",
    "//",
    "Функция ЭтоБазаРозницы()",
    "\t",
    "\tВозврат СтрНайти(ВРег(Константы.ЗаголовокСистемы.Получить()), \"RETAIL\") > 0;",
    "\t",
    "КонецФункции",
    "",
    "#КонецОбласти",
    "",
    "",
])


def insert_after(text, anchor, addition):
    assert text.count(anchor) == 1, anchor
    return text.replace(anchor, anchor + addition)


def main():
    text = open(MODULE, "rb").read().decode("utf-8-sig").replace("\r\n", "\n")
    assert 'ПараметрыРегистрации.Версия = "1.19";' in text, "исходник не 1.19 или уже изменен"

    text = insert_after(text, "Процедура ВыполнитьКоманду(ИдентификаторКоманды, ПараметрыВыполненияКоманды) Экспорт\n\t\n",
                        RETURN_IN_COMMAND)
    text = insert_after(text, "Процедура ЗаполнитьДепозиты(Лог) Экспорт\n\t\n", RETURN_WITH_LOG)
    text = insert_after(text, "Процедура ЗаполнитьДепозитыАванкор(Лог) Экспорт\n\t\n", RETURN_WITH_LOG)
    text = insert_after(text, "Процедура ЗаполнитьДепозитыКалипсоМодуль(Лог) Экспорт\n\t\n", RETURN_PLAIN)
    anchor = "#Область Заполнение\n"
    assert text.count(anchor) == 1
    text = text.replace(anchor, NEW_REGION + anchor)
    text = text.replace('ПараметрыРегистрации.Версия = "1.19";', 'ПараметрыРегистрации.Версия = "1.20";')

    open(MODULE, "wb").write(b"\xef\xbb\xbf" + text.replace("\n", "\r\n").encode("utf-8"))
    print("ok", MODULE)


if __name__ == "__main__":
    main()
