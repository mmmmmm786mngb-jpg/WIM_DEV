def time_check(variant):
    checks = [step(variant, name)["сверка_времени"] for name in ("Покупка.ФормаФон", "Продажа.ФормаФон")]
    total = sum(c["цен_с_биржи"] for c in checks)
    ok = sum(c["в_допуске_1с"] for c in checks)
    worst = max([d["до_ближайшего_ответа_с"] for c in checks for d in c["детали"]] or [0])
    return total, ok, worst


