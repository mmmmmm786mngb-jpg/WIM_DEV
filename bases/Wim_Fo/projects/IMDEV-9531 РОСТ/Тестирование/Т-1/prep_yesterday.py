# -*- coding: utf-8 -*-
"""Позиции выборки T9531PROP на прошлый день для тестового режима РОСТ на dev ФО.

Тестовый режим РОСТ берет позиции строго на вчерашнюю дату (РегистрСведений.ФактическаяПозиция, Дата = вчера), поэтому
в новый день списки реинвестирования и блокировок пустые. Скрипт копирует позиции последней даты с полным набором
выборки на вчера - только портфелям, у которых на вчера позиций нет (портфели блокировок, подготовленные
../1_21/prepare_blocks.py, не затрагиваются). Регистр независимый, записи добавляются (Записать(Ложь)).

Порядок в новый день: python prep_yesterday.py, затем ../1_21/prepare_blocks.py 500, затем снова prep_yesterday.py
(prepare_blocks замещает позиции 500 портфелей на вчера, остальные копируются этим скриптом).

    python prep_yesterday.py
"""
import datetime
import os
import sys

sys.stdout.reconfigure(encoding="utf-8")
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(os.path.dirname(HERE), "1_18"))
import run_1_18_tests as base  # noqa: E402

FIELDS = ("Количество, Стоимость, АмортизированнаяСтоимость, НКД, Задолженность, СуммаДенежныхСредствСЗадолженностью, "
          "ПервоначальнаяСтоимость, Портфель, Актив, МестоХранения, Субпортфель, ДатаПартии, ТипПортфеля, СчетУчета")

fo = base.stage4.connect("wim_fo")
today = datetime.date.today()
yesterday = today - datetime.timedelta(days=1)
# Дата литералом в тексте запроса: datetime через COM смещается на часовой пояс (22.10 0:00 приходит как 21.10).
YESTERDAY = "ДАТАВРЕМЯ(%d, %d, %d)" % (yesterday.year, yesterday.month, yesterday.day)

query = fo.NewObject("Запрос")
query.Текст = """ВЫБРАТЬ
    МАКСИМУМ(т.Дата) КАК Дата
ИЗ
    РегистрСведений.ФактическаяПозиция КАК т
ГДЕ
    т.Портфель.ВнешнийКод ПОДОБНО "T9531PROP%"
    И т.Дата < """ + YESTERDAY + """"""
selection = query.Выполнить().Выбрать()
selection.Следующий()
source = selection.Дата
print("источник", fo.String(source), "-> вчера", yesterday)

query.УстановитьПараметр("Источник", source)
query.Текст = """ВЫБРАТЬ РАЗЛИЧНЫЕ
    т.Портфель КАК Портфель
ПОМЕСТИТЬ ВТЕсть
ИЗ
    РегистрСведений.ФактическаяПозиция КАК т
ГДЕ
    т.Дата = """ + YESTERDAY + """
    И т.Портфель.ВнешнийКод ПОДОБНО "T9531PROP%"
ИНДЕКСИРОВАТЬ ПО
    Портфель
;
ВЫБРАТЬ
    """ + YESTERDAY + """ КАК Дата,
    """ + ",\n    ".join("т." + f.strip() + " КАК " + f.strip() for f in FIELDS.split(",")) + """
ИЗ
    РегистрСведений.ФактическаяПозиция КАК т
        ЛЕВОЕ СОЕДИНЕНИЕ ВТЕсть КАК СПозицией
        ПО т.Портфель = СПозицией.Портфель
ГДЕ
    т.Дата = &Источник
    И т.Портфель.ВнешнийКод ПОДОБНО "T9531PROP%"
    И СПозицией.Портфель ЕСТЬ NULL"""
table = query.Выполнить().Выгрузить()
print("строк к копированию", table.Количество())
if table.Количество():
    records = fo.РегистрыСведений.ФактическаяПозиция.СоздатьНаборЗаписей()
    records.Загрузить(table)
    records.Записать(False)
query.Текст = """ВЫБРАТЬ
    КОЛИЧЕСТВО(РАЗЛИЧНЫЕ т.Портфель) КАК Портфелей,
    КОЛИЧЕСТВО(*) КАК Строк
ИЗ
    РегистрСведений.ФактическаяПозиция КАК т
ГДЕ
    т.Дата = """ + YESTERDAY + """
    И т.Портфель.ВнешнийКод ПОДОБНО "T9531PROP%\""""
selection = query.Выполнить().Выбрать()
selection.Следующий()
print("на вчера: портфелей", selection.Портфелей, "строк", selection.Строк)
