def requests(variant, names):
    return "/".join(str(step(variant, s)["запросов_стакана"]) for s in names)


def single(variant, name, orders):
    s = step(variant, name)
    actual = "%s; этапы: %s; поручений в последнем сообщении %d; последнее сообщение с ценами: %s" % (
        s["состояние"], " -> ".join(s["этапы"]), s["поручений_в_последнем_снимке"],
        "да" if s["последнее_сообщение_с_ценами"] else "нет")
    ok = (s["состояние"] == "Задание выполнено" and s["этапы"] == STAGES and s["поручений_в_последнем_снимке"] == orders
          and s["последнее_сообщение_с_ценами"] and not s["ошибка"])
    return actual, ok


def threads(variant):
    s = step(variant, "Реинвест.ПотокиФормы")
    th = list(s["потоки"].values())
    all_last = all(t["последнее_сообщение_с_ценами"] for t in th)
    all_done = all(t["этапы"][-1] == "Поручения потока созданы" for t in th)
    actual = ("потоков %d, поручений %d, в последних сообщениях потоков %d; у всех потоков последний этап "
              "\"Поручения потока созданы\": %s; последнее сообщение с ценами: %s; отправка пачки: %s") % (
        s["потоков"], s["поручений"], s["поручений_в_последних_снимках"], "да" if all_done else "нет",
        "да" if all_last else "нет", s["отправка"]["состояние"])
    ok = (s["потоков"] == 10 and s["поручений"] == 200 == s["поручений_в_последних_снимках"] and all_last and all_done
          and s["отправка"]["состояние"] == "Задание выполнено" and not s["потоки_без_результата"])
    return actual, ok


def own_messages(variant):
    """Сообщения прогресса обработки (без сообщений конфигурации): покупка, продажа, максимум на поток."""
    p, s = step(variant, "Покупка.ФормаФон"), step(variant, "Продажа.ФормаФон")
    th = step(variant, "Реинвест.ПотокиФормы")["потоки"].values()
    values = (p["сообщений_прогресса"] - p["сообщений_конфигурации"], s["сообщений_прогресса"] - s["сообщений_конфигурации"],
              max(t["сообщений_прогресса"] - t["сообщений_конфигурации"] for t in th))
    return values


def sources(variant):
    found = set()
    for name in FORM_STEPS[:2]:
        found |= set(step(variant, name)["источники"])
    for t in step(variant, "Реинвест.ПотокиФормы")["потоки"].values():
        found |= set(t["источники"])
    return sorted(found)


