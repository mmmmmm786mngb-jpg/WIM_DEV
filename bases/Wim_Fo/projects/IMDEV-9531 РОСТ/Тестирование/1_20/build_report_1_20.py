def boost(keys):
    before, after = step(base, keys[0])["длительность_с"], step(form60, keys[1])["длительность_с"]
    return before / after, before - after, (before - after) / before * 100


def boost_tiles():
    tiles = []
    for keys, title in SCEN:
        ratio, saved, share = boost(keys)
        tiles.append('<div class="tile"><div class="tile-x">в %s раза</div><div class="tile-t">%s</div>'
                     '<div class="tile-s">%s с вместо %s с, время меньше на %d%%</div></div>' % (
                         ru(ratio), e(title), ru(step(form60, keys[1])["длительность_с"]),
                         ru(step(base, keys[0])["длительность_с"]), round(share)))
    return "\n".join(tiles)


def speed_rows():
    rows = []
    for keys, title in SCEN:
        b, h, f6, f0 = (step(base, keys[0]), step(harness, keys[0]), step(form60, keys[1]), step(form0, keys[1]))
        ratio, saved, share = boost(keys)
        rows.append("<tr><td>%s</td><td class=n>%s</td><td class=n>%s</td><td class=n>%s</td><td class=n>%s</td>"
                    "<td class=boost><span class=x>в %s раза</span><span class=sub>на %s с быстрее, время меньше на %d%%"
                    "</span></td><td class=n>%s / %s / %s</td></tr>" % (
                        e(title), ru(b["длительность_с"]), ru(h["длительность_с"]), ru(f6["длительность_с"]),
                        ru(f0["длительность_с"]), ru(ratio), ru(saved), round(share),
                        b["запросов_стакана"], f6["запросов_стакана"], f0["запросов_стакана"]))
    return "\n".join(rows)


