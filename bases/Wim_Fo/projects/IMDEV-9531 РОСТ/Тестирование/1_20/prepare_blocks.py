# -*- coding: utf-8 -*-
"""Данные для продаж под блокировки на выборке T9531PROP (dev ФО).

Выборка T9531PROP продаж под блокировки не содержит. Сценарий "Данные" обвязки T9530_ТестРОСТ (группа "Б") для
последних N портфелей реинвестирования (коды T9531PROP_R по убыванию): позиция ВИМ Ликвидность 100000 на прошлый
торговый день (замещает позицию портфеля на эту дату, портфель выпадает из списка реинвестирования), неторговое
поручение на вывод сегодня 50000 + i*1000 руб., статус "Окончание обработки". После этого закладка формы
"Продажи под блокировки" (вариант LQDT) показывает эти портфели с отрицательным остатком денег.

Свойства статуса, статус и актив ликвидности берутся из настроек зарегистрированной обработки РОСТ.

    python prepare_blocks.py [N]      N - число портфелей, по умолчанию 60
"""
import os
import sys

sys.stdout.reconfigure(encoding="utf-8")
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import run_1_20_tests as r  # noqa: E402

stage4 = r.stage4


def main():
    count = int(sys.argv[1]) if len(sys.argv) > 1 else 60
    fo = stage4.connect("wim_fo")
    test_ref = r.base.harness_ref(fo)
    rost_ref = stage4.find_ref(
        fo, "ВЫБРАТЬ Д.Ссылка КАК Ссылка ИЗ Справочник.ДополнительныеОтчетыИОбработки КАК Д "
            "ГДЕ Д.ИмяОбъекта = &Имя И НЕ Д.ПометкаУдаления", {"Имя": stage4.ROST_OBJECT})
    settings = rost_ref.ХранилищеНастроек.Получить()
    rows = stage4.query(fo, """ВЫБРАТЬ ПЕРВЫЕ %d П.ВнешнийКод КАК Код, П.Ссылка КАК Портфель, С.Ссылка КАК Субпортфель,
            С.МестоХранения КАК Место
        ИЗ Справочник.Портфели КАК П ВНУТРЕННЕЕ СОЕДИНЕНИЕ Справочник.Субпортфели КАК С ПО С.Портфель = П.Ссылка
        ГДЕ П.ВнешнийКод ПОДОБНО "T9531PROP_R%%" УПОРЯДОЧИТЬ ПО П.ВнешнийКод УБЫВ""" % count)
    portfolios = fo.NewObject("Массив")
    for idx, row in enumerate(rows, start=1):
        portfolios.Добавить(r.struct(fo, Портфель=row["Портфель"], Субпортфель=row["Субпортфель"],
                                     МестоХранения=row["Место"], Группа="Б", Активен=True, Сумма=50000 + idx * 1000))
    statuses = r.struct(fo, Поиск=settings.СтатусДляПоиска, Расторжение=settings.СтатусРасторжениеИнициировано,
                        Окончание=settings.СтатусОкончаниеОбработки)
    params = r.struct(fo, Сценарий="Данные", Портфели=portfolios, Свойство=settings.ДопРеквизитСтатусПортфеля,
                      СвойствоДата=settings.ДопРеквизитДатаОперации, Статусы=statuses, АктивРубли=stage4.rub_asset(fo),
                      АктивОблигация=settings.АктивВимЛиквидность, АктивЛиквидность=settings.АктивВимЛиквидность,
                      АктивыПродажи=fo.NewObject("Массив"))
    out = stage4.run_harness(fo, test_ref, params, "данные блокировок T9531PROP", timeout=1800)
    print("portfolios", len(rows), fo.String(rows[0]["Код"]), "..", fo.String(rows[-1]["Код"]), out.get("состояние"),
          (out.get("ошибка") or out.get("ошибка_задания") or "")[:500], out.get("даты"))

    obj = r.rost_object(fo, rost_ref)
    obj.БлокировкиПродажиОбновитьСписокПотфелей("LQDT", True, "", 0)
    rows = obj.СписокПортфелейПродажиПодБлокировки
    negative = sum(1 for i in range(rows.Количество()) if float(rows.Получить(i).ОстатокДС) < 0)
    print("blocks list", rows.Количество(), "with negative cash", negative)


if __name__ == "__main__":
    main()
