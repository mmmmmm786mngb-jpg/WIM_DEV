def replace_once(text, old, new, what):
    assert text.count(old) == 1, "%s: найдено %d" % (what, text.count(old))
    return text.replace(old, new)


def procedure_bounds(text, header):
    start = text.index(header)
    end = text.index("\nКонецПроцедуры", start)
    return start, end


def patch_thread(text, header, operation):
    start, end = procedure_bounds(text, header)
    body = text[start:end]
    anchor = "\tНомерПотока = Параметры.НомерПотока;\n"
    assert body.count(anchor) == 1, header
    body = body.replace(anchor, anchor +
                        "\t// IMDEV-9531 СБОРКА Т-1: журнал хода потока\n"
                        "\tНачалоПотокаТ1 = ТекущаяУниверсальнаяДатаВМиллисекундах();\n"
                        "\tСчетчикТ1 = 0;\n"
                        '\tЖурналТ1("ПотокСтарт", СтрШаблон("%%1; поток %%2; портфелей %%3", "%s", НомерПотока, '
                        'Параметры.ПортфелиСписок.Количество()));\n' % operation)
    loop = "\tДля каждого СтрокаПортфель Из ПортфелиСписок Цикл\n"
    assert body.count(loop) == 1, header + " цикл"
    body = body.replace(loop, loop +
                        "\t\t// IMDEV-9531 СБОРКА Т-1: ход потока\n"
                        "\t\tСчетчикТ1 = СчетчикТ1 + 1;\n"
                        '\t\tПрогрессПотокаТ1("%s", НомерПотока, СчетчикТ1, ПортфелиСписок.Количество(), '
                        "ПорученияНаОтправку.Количество(), НачалоПотокаТ1);\n" % operation)
    put = "\tПоместитьВоВременноеХранилище(СтруктураОтвета, АдресВоВременномХранилище);"
    assert body.count(put) == 1, header + " результат"
    finish = ("\t// IMDEV-9531 СБОРКА Т-1: финиш потока и его лог\n"
              '\tЖурналТ1("ПотокФиниш", СтрШаблон("%1; поток %2; портфелей %3; создано %4; %5 с", "{op}", '
              "НомерПотока, СчетчикТ1, ПорученияНаОтправку.Количество(), "
              'Формат((ТекущаяУниверсальнаяДатаВМиллисекундах() - НачалоПотокаТ1) / 1000, '
              '"ЧДЦ=1; ЧН=0; ЧГ=0")));\n'
              '\tЖурналТ1("ПотокЛог", "{op}; поток " + НомерПотока + Символы.ПС + '
              "Лев(ЭтотОбъект.Лог.ПолучитьТекст(), 30000));\n").replace("{op}", operation)
    body = body.replace(put, finish + put)
    return text[:start] + body + text[end:]


def patch(text, version):
    text = text.replace("\r\n", "\n")
    text = replace_once(text, '\tПараметрыРегистрации.Версия = "%s";' % version,
                        '\tПараметрыРегистрации.Версия = "%s-т1";' % version, "версия")
    text = replace_once(text, "\nЭтоТест = Ложь;", "\n// IMDEV-9531 СБОРКА Т-1: тестовый режим\nЭтоТест = Истина;",
                        "тело модуля")
    text = replace_once(text, "\tУказания.ОтправитьПослеПроверки = Истина;",
                        "\t// IMDEV-9531 СБОРКА Т-1: в тестовом режиме проверка лимитов без отправки на биржу\n"
                        "\tУказания.ОтправитьПослеПроверки = Не ЭтоТест;", "отправка")
    text = replace_once(text, "\tРезультатПроверки = Распорядители.ПроверкаИОтправка(Указания);\n",
                        "\t// IMDEV-9531 СБОРКА Т-1: журнал отправки пачки\n"
                        "\tНачалоПачкиТ1 = ТекущаяУниверсальнаяДатаВМиллисекундах();\n"
                        '\tЖурналТ1("ПачкаСтарт", "поручений " + СписокПоручений.Количество());\n'
                        "\tРезультатПроверки = Распорядители.ПроверкаИОтправка(Указания);\n"
                        '\tЖурналТ1("ПачкаФиниш", СтрШаблон("поручений %1; %2 с", СписокПоручений.Количество(), '
                        'Формат((ТекущаяУниверсальнаяДатаВМиллисекундах() - НачалоПачкиТ1) / 1000, '
                        '"ЧДЦ=1; ЧН=0; ЧГ=0")));\n', "пачка")

    start = text.index("Функция ИзменитьЦенуПорученияТест(")
    query = text.index("Запрос = новый запрос;", start)
    line_start = text.rindex("\n", 0, query) + 1
    indent = text[line_start:query]
    text = text[:query] + "ПаузаСтаканаТ1(); // IMDEV-9531 СБОРКА Т-1\n" + indent + text[query:]
    text = text[:start] + HELPERS + text[start:]

    load = "\tСписокПортфелейПродажиПодБлокировки.Загрузить(Запрос.Выполнить().Выгрузить());"
    text = replace_once(text, load, ORDER + load, "блокировки")
    start, end = procedure_bounds(text, "Процедура РеинвестОбновитьСписокПотфелей(")
    body = text[start:end]
    tail = "СуммаПодКомисси;\n\t\t\n\tКонецЦикла;\n"
    assert body.count(tail) == 1, "сумма реинвестирования"
    body = body.replace(tail, tail + "\t\n" + ORDER_SUM)
    text = text[:start] + body + text[end:]

    text = patch_thread(text, "Процедура РеинвестСоздатьОрдера(", "Реинвест")
    text = patch_thread(text, "Процедура БлокировкиПродажиСоздатьОрдера(", "Блокировки")
    return text.replace("\n", "\r\n")


def patch_form(text):
    text = text.replace("\r\n", "\n")
    first = text.index("&НаКлиенте\nПроцедура ПослеЗавершенияСозданияПорученийРеинвестирование(")
    text = text[:first] + FORM_HELPERS + text[first:]
    for name in ("ПослеЗавершенияСозданияПорученийРеинвестирование", "ПослеЗавершенияСозданияПорученийПродажиБлок"):
        header = text.index("Процедура %s(" % name)
        line_end = text.index("\n", header) + 1
        text = text[:line_end] + "\n\tЗаписатьСостояниеПотокаТ1(Задание); // IMDEV-9531 СБОРКА Т-1\n" + text[line_end:]
    return text.replace("\n", "\r\n")


def rewrite(path, func, *args):
    with open(path, "r", encoding="utf-8-sig") as handle:
        text = handle.read()
    with open(path, "w", encoding="utf-8-sig", newline="") as handle:
        handle.write(func(text, *args))


def main():
    for version, folder in BUILDS.items():
        src = os.path.join(TASK, folder, "внСозданиеТорговыхПорученийРОСТ_epf")
        dst = os.path.join(HERE, "сборки", version + "-т1")
        if os.path.exists(dst):
            shutil.rmtree(dst)
        shutil.copytree(src, dst)
        rewrite(os.path.join(dst, MODULE), patch, version)
        rewrite(os.path.join(dst, FORM_MODULE), patch_form)
        epf = os.path.join(HERE, "РОСТ_%s-т1.epf" % version)
        result = subprocess.run(["powershell.exe", "-NoProfile", "-File", EPF_BUILD, "-Checks", "off",
                                 "-SourceFile", os.path.join(dst, ROOT_XML), "-OutputFile", epf],
                                capture_output=True, text=True, encoding="utf-8", errors="replace")
        ok = result.returncode == 0 and os.path.exists(epf)
        print(version, "ok" if ok else "ОШИБКА СБОРКИ", epf)
        if not ok:
            print(result.stdout[-2000:], result.stderr[-2000:])


if __name__ == "__main__":
    main()
