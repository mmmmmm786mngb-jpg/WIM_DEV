def replace_once(text, old, new, title):
    count = text.count(old)
    if count != 1:
        raise SystemExit(title + " count=" + str(count))
    return text.replace(old, new, 1)


def replace_first(text, old, new, title):
    index = text.find(old)
    if index < 0:
        raise SystemExit(title + " missing")
    return text[:index] + new + text[index + len(old):]


