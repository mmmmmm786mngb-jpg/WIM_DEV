function code(lines) {
  return lines.map((l, i) => new Paragraph({
    children: [new TextRun({ text: l.replace(/\t/g, "    ") || " ", font: MONO, size: 17 })],
    shading: { type: ShadingType.CLEAR, fill: "F2F3F5", color: "auto" },
    spacing: { before: i === 0 ? 80 : 0, after: i === lines.length - 1 ? 160 : 0, line: 240 },
    indent: { left: 120, right: 120 },
  }));
}

