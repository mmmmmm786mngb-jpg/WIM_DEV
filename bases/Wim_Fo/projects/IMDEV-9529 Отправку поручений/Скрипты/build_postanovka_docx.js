function table(headers, rows, widths, opts = {}) {
  const total = widths.reduce((a, b) => a + b, 0);
  const mk = (text, w, header, fill) => new TableCell({
    width: { size: w, type: WidthType.DXA }, borders,
    shading: header ? { type: ShadingType.CLEAR, fill: "DCE6F0", color: "auto" }
      : fill ? { type: ShadingType.CLEAR, fill, color: "auto" } : undefined,
    margins: { top: 60, bottom: 60, left: 100, right: 100 },
    children: String(text).replace(/([А-Яа-яA-Za-z_])\.(?=[А-Яа-яA-Za-z_])/g, "$1.​").split("\n").map(line => new Paragraph({
      children: runs(line, header ? { bold: true, size: 19 } : { size: 19 }),
      alignment: AlignmentType.LEFT,
    })),
  });
  return new Table({
    width: { size: total, type: WidthType.DXA }, columnWidths: widths, layout: TableLayoutType.FIXED,
    rows: [
      new TableRow({ tableHeader: true, children: headers.map((h, i) => mk(h, widths[i], true)) }),
      ...rows.map((r, ri) => new TableRow({ children: r.map((c, i) => mk(c, widths[i], false, (opts.highlight || []).includes(ri) ? "EAF4EC" : undefined)) })),
    ],
  });
}
