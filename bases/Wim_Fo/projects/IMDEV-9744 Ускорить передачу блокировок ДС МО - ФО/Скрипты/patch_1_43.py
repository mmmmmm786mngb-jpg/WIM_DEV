ANCHOR_PROCEDURES = "Процедура ОпубликоватьАктивыРЕПО(ФабрикаСервиса, Прокси, ДатаИсполнения = Неопределено, ТЗИсточник)"


def replace_once(text, old, new):
    assert text.count(old) == 1, old[:80]
    return text.replace(old, new)


def main():
    raw = open(MODULE, "rb").read()
    text = raw.decode("utf-8-sig").replace("\r\n", "\n")
    assert 'ПараметрыРегистрации.Вставить("Версия", "1.42");' in text, "исходник уже изменен или не 1.42"

    # Старая ветка блокировок: от комментария "выгрузка блокировок" до КонецЕсли ветки Иначе (удаление блокировок).
    lines = text.split("\n")
    start = lines.index("\t\t\t// выгрузка блокировок")
    end = start + lines[start:].index(
        "\t\t\t\tМассивКодовПортфелейДляУдаленияБлокировок.Добавить(ВыборкаПортфели.Мандат.КодМандата);") + 1
    assert lines[end] == "\t\t\tКонецЕсли;", lines[end]
    assert "ВызватьDownloadOrders" in "\n".join(lines[start:end]), "в заменяемом блоке нет вызова DownloadOrders"
    text = "\n".join(lines[:start]) + "\n" + NEW_BLOCKS + "\n".join(lines[end + 1:])

    text = replace_once(text, REMOVE_CALL, SEND_PACKET_CALL + REMOVE_CALL)
    text = replace_once(text, INIT, INIT + INIT_ADD)
    text = replace_once(text, AFTER_LOOP, AFTER_LOOP.replace("\t\n", "\t\n" + AFTER_LOOP_ADD, 1))
    text = replace_once(text, ANCHOR_PROCEDURES, PROCEDURES + ANCHOR_PROCEDURES)
    text = replace_once(text, 'ПараметрыРегистрации.Вставить("Версия", "1.42");',
                        'ПараметрыРегистрации.Вставить("Версия", "1.43");')

    open(MODULE, "wb").write(b"\xef\xbb\xbf" + text.replace("\n", "\r\n").encode("utf-8"))
    print("ok", MODULE)


if __name__ == "__main__":
    main()
