    raw_n = raw.replace("\r\n", "\n").replace("\r", "\n")
    method = extract_method(raw_n)
    bsl = build_interceptor(method)
    EXT_MODULE.parent.mkdir(parents=True, exist_ok=True)
    EXT_MODULE.write_text("\ufeff" + bsl.replace("\n", "\r\n"), encoding="utf-8")
    print("wrote", EXT_MODULE)
