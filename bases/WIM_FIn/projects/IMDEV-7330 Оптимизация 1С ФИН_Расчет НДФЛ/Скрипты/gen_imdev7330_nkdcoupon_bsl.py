def extract_method(text: str) -> str:
    start = text.find("Функция РасходыПоНКДПоКлиентамИДате(ВидыОбращаемости, МассивКлиентов, Дата)")
    if start < 0:
        raise SystemExit("method start not found")
    end = text.find("КонецФункции", start)
    if end < 0:
        raise SystemExit("method end not found")
    return text[start : end + len("КонецФункции")]


def split_query_assignment(method: str):
    marker = "\tЗапрос.Текст ="
    pos = method.find(marker)
    if pos < 0:
        raise SystemExit("Запрос.Текст not found")
    # assignment is Запрос.Текст =\n\t"....";
    rest = method[pos:]
    m = re.match(r'\tЗапрос\.Текст =\n\t"(.*?)"\;', rest, re.S)
    if not m:
        raise SystemExit("query string assignment did not match")
    old_inner = m.group(1)
    before = method[:pos]
    after = rest[m.end() :]
    return before, old_inner, after


def build_interceptor(method: str) -> str:
    before, old_inner, after = split_query_assignment(method)
    # Хвост с РезультирующаяТаблица без изменений: отрезаем его от старого пакета и клеим к новому префиксу.
    tail_mark = "ВЫБРАТЬ\n\t|	ВТ_РасходыПоНКД.Счет КАК Счет,"
    idx = old_inner.find(tail_mark)
    if idx < 0:
        raise SystemExit("tail marker РезультирующаяТаблица not found in original query")
    old_tail = old_inner[idx:]
    new_inner = NEW_INNER + old_tail
    wrapped = (
        before
        + "\t#Удаление\n"
        + "\tЗапрос.Текст =\n\t\""
        + old_inner
        + "\";\n"
        + "\t#КонецУдаления\n"
        + "\t#Вставка\n"
        + "\t// IMDEV-7330 Оплаченные купоны привязаны к клиенту; ПереводНКД соединяется по паре (Клиент, Купон).\n"
        + "\tЗапрос.Текст =\n\t\""
        + new_inner
        + "\";\n"
        + "\t#КонецВставки"
        + after
    )
    wrapped = wrapped.replace(
        "Функция РасходыПоНКДПоКлиентамИДате(ВидыОбращаемости, МассивКлиентов, Дата)",
        'Функция IMDEV7330_NkdCoupon_РасходыПоНКДПоКлиентамИДате(ВидыОбращаемости, МассивКлиентов, Дата)',
        1,
    )
    header = (
        "#Если Сервер Или ТолстыйКлиентОбычноеПриложение Или ВнешнееСоединение Тогда\n"
        "\n"
        "// IMDEV-7330 Массовый запрос расходов НКД: купон ПереводНКД только если его оплатил тот же клиент.\n"
        "\n"
        '&ИзменениеИКонтроль("РасходыПоНКДПоКлиентамИДате")\n'
    )
    return header + wrapped + "\n\n#КонецЕсли\n"


def patch_document_xml(path: Path) -> None:
    xml = path.read_text(encoding="utf-8-sig")
    marker = (
        "\t\t\t<xr:PropertyState>\n"
        "\t\t\t\t<xr:Property>ManagerModule</xr:Property>\n"
        "\t\t\t\t<xr:State>Extended</xr:State>\n"
        "\t\t\t</xr:PropertyState>\n"
    )
    if "ManagerModule</xr:Property>" in xml:
        print("PropertyState ManagerModule already present")
        return
    needle = "\t\t</InternalInfo>"
    if needle not in xml:
        raise SystemExit("InternalInfo close not found")
    xml = xml.replace(needle, marker + needle, 1)
    path.write_text(xml, encoding="utf-8-sig", newline="\n")
    print("patched PropertyState ManagerModule:", path)


