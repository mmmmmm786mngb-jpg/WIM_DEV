def retarget(block, orig_start, new_header, decorator_name):
    """Replace first line (procedure/function header) with decorator + new header."""
    parts = block.splitlines(keepends=True)
    rest = "".join(parts[1:])
    return f'&ИзменениеИКонтроль("{decorator_name}")\n{new_header}\n' + rest


